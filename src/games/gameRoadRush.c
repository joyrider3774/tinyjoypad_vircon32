void drvRenderFrame( void )
{
    md_beginFrame();
    int col, page;
    for( page = 0; page < 8; page++ )
      for( col = 0; col < 128; col++ )
        md_drawColumn( col, page, drvFrameBuffer[ col + ( page * 128 ) ] );
}

void gameRoadRush_init( void )
{
    InitTinyJoypad();
    drvState = DRV_STATE_ATTRACT;
    drvTickSkipCounter = 0;
    drvStateTicks = 0;
    drvPrevFire = 0;
    drvFireEdge = 0;
    drvLevel = 1;
    drvClearBuffer();
}

void gameRoadRush_update( void )
{
    drvTickSkipCounter = drvTickSkipCounter + 1;
    if( drvTickSkipCounter < DRV_TICK_DIVISOR ) return;
    drvTickSkipCounter = 0;

    drvStateTicks = drvStateTicks + 1;

    int fireNow = isFirePressed();
    drvFireEdge = fireNow && !drvPrevFire;
    drvPrevFire = fireNow;

    drvKeyAccelerate = isUpPressed();
    drvKeyBrake = isDownPressed();
    drvKeyLeft = isLeftPressed();
    drvKeyRight = isRightPressed();

    if( drvState == DRV_STATE_ATTRACT ) drvUpdateAttract();
    else if( drvState == DRV_STATE_FLAG ) drvUpdateFlag();
    else if( drvState == DRV_STATE_INTRO_SCROLL ) drvUpdateIntroScroll();
    else if( drvState == DRV_STATE_LEVEL_SLIDER ) drvUpdateLevelSlider();
    else if( drvState == DRV_STATE_PLAYING ) drvUpdatePlaying();
    else if( drvState == DRV_STATE_WIN_LOSE ) drvUpdateWinLose();
    else drvUpdateOutroScroll();

    drvRenderFrame();
}

void gameRoadRush_forceRedraw( void )
{
    if( drvState == DRV_STATE_ATTRACT ) drvDrawAttract();
    else if( drvState == DRV_STATE_PLAYING ) drvDisplayDrive();
    else if( drvState == DRV_STATE_LEVEL_SLIDER ) drvDisplayLevelSlider();
    else if( drvState == DRV_STATE_WIN_LOSE ) drvDisplayWinLose();
    else if( drvState == DRV_STATE_INTRO_SCROLL ) drvDrawScrollerIntro();
    else if( drvState == DRV_STATE_OUTRO_SCROLL ) drvDrawScrollerOutro();
    drvRenderFrame();
}
