// -----------------------------------------------------------------------------
// Driving gameplay update - direct 1:1 port of updateDrive(), running at
// the real DRV_TICK_DIVISOR-throttled ~30fps rate so every constant below
// (carSpeed deltas, distance-per-tick, the 30-tick udpateSpeed threshold,
// turnDepth countdown) needs no rescaling at all.
// -----------------------------------------------------------------------------

#define DRV_MAX_OFFROAD_SPEED 25
#define DRV_MAX_ROAD_SPEED 70
#define DRV_UPDATE_SPEED 30

int drvUpdateDrive( void )
{
    if( drvPlayerX < 128 / 5 || drvPlayerX + DRV_PLAYER_W > 128 - ( 128 / 5 ) )
    {
        if( DRV_MAX_OFFROAD_SPEED < drvCarSpeed ) drvCarSpeed = drvCarSpeed - 2;
    }

    if( drvCollision )
    {
        drvCarSpeed = 0;
        drvCollision = 0;
    }

    if( drvKeyAccelerate )
    {
        drvCarSpeed = drvCarSpeed + 1;
    }
    else
    {
        if( drvStateTicks % 20 == 0 ) drvCarSpeed = drvCarSpeed - 1;
    }

    if( drvKeyBrake ) drvCarSpeed = drvCarSpeed - 1;
    if( drvCarSpeed < 0 ) drvCarSpeed = 0;
    if( drvCarSpeed > DRV_MAX_ROAD_SPEED ) drvCarSpeed = DRV_MAX_ROAD_SPEED;

    if( drvKeyLeft ) drvPlayerX = drvPlayerX - 1;
    if( drvKeyRight ) drvPlayerX = drvPlayerX + 1;

    if( !drvTurning )
    {
        drvTurning = arand( 100 ) == 0;
        if( drvTurning )
        {
            if( drvTurningLeft ) drvTurningLeft = 0; else drvTurningLeft = 1;
            drvTurnDepth = arand( 100 );
        }
    }

    drvRoadSpeed = DRV_MAX_ROAD_SPEED + 1 - drvCarSpeed;
    drvDistance = drvDistance + ( drvCarSpeed / 8 );

    if( drvTurning )
    {
        if( drvDistance - drvLastDistance >= DRV_UPDATE_SPEED )
        {
            if( drvTurningLeft ) drvPlayerX = drvPlayerX + 1; else drvPlayerX = drvPlayerX - 1;

            if( drvTurnDepth > 0 )
            {
                if( drvTurningLeft ) drvTurnOffset = drvTurnOffset - 1; else drvTurnOffset = drvTurnOffset + 1;
                drvTurnDepth = drvTurnDepth - 1;
            }

            if( drvTurnDepth == 0 )
            {
                if( drvTurnOffset == 0 )
                {
                    drvTurning = 0;
                }
                else
                {
                    if( drvTurningLeft ) drvTurnOffset = drvTurnOffset + 1; else drvTurnOffset = drvTurnOffset - 1;
                }
            }

            if( drvTurnOffset < -47 ) drvTurnOffset = -47;
            if( drvTurnOffset > 47 ) drvTurnOffset = 47;
        }
    }

    if( drvPlayerX < 0 ) drvPlayerX = 0;
    else if( drvPlayerX + DRV_PLAYER_W > 128 ) drvPlayerX = 128 - DRV_PLAYER_W;

    if( drvDistance - drvLastDistance >= DRV_UPDATE_SPEED )
    {
        if( drvEvenLines ) drvEvenLines = 0; else drvEvenLines = 1;
        drvLastDistance = drvDistance;
    }

    int i;
    for( i = 0; i < drvMaxCars; i++ )
    {
        if( drvCars[ i ].y == 0 || drvCars[ i ].y == 64 )
        {
            drvInitCar( i );
        }
        else
        {
            drvCars[ i ].distance = drvCars[ i ].distance + drvCars[ i ].speed;

            if( drvCars[ i ].distance - drvDistance >= DRV_UPDATE_SPEED )
            {
                drvCars[ i ].distance = drvDistance;
                drvCars[ i ].y = drvCars[ i ].y - 1;
            }
            if( drvDistance - drvCars[ i ].distance >= DRV_UPDATE_SPEED )
            {
                drvCars[ i ].distance = drvDistance;
                drvCars[ i ].y = drvCars[ i ].y + 1;
            }
        }
    }

    if( drvStateTicks > drvStageTime * DRV_FPS )
    {
        drvWin = 0;
        return 0;
    }
    if( drvStageDistance - ( drvDistance / 8 ) < 0 )
    {
        drvWin = 1;
        return 0;
    }

    return 1;
}

