// Road Rush (Tony M / "tonym128", GPLv3). A top-down perspective driving
// game - steer left/right and accelerate/brake down a curving road, dodge
// oncoming traffic scaled by distance (further cars draw smaller), reach
// the stage's own target distance before time runs out across 2 stages of
// rising difficulty (more cars, longer distance/time).
//
// Ported from `more games/BFlight/driveGame.cpp`/`.hpp` - one of several
// mini-games bundled in tonym128's own "BFlight" game framework, itself
// built on the BSides Cape Town 2016 CTF badge hardware
// (`AndrewMohawk/BSidesBadge2016`). See this project's own CLAUDE.md
// "sixth beyond-scope discovery pass" for how this was found (a follow-up
// search specifically for ESP8266/ESP8285 OLED handheld games once Daniel
// C's own ESP-compilation proved that whole hardware class ports as
// cleanly as ATtiny85). Menu title "ROAD RUSH" is lifted directly from
// the game's own in-source credit text (the intro scroller's own
// " -= Road Rush =-" line), the same "read the game's own on-screen text
// for its real name" approach already used for Bat Bonanza/Falling
// Blocks. Confirmed via both this project's own research and direct
// reading to be a genuinely new genre for this cartridge - nothing else
// here is a top-down perspective driving/dodging game (Tiny Bike is a
// structurally different side-scrolling motocross game).
//
// ***A genuinely different rendering foundation from every other
// tinyJoypadShim/obonoCoreShim-lineage game in this cartridge, but the
// same one already proven for Gilbert in the Downland/Tiny Arena***:
// upstream's own `ScreenBuff.consoleBuffer[8192]` is a full, real,
// per-pixel-addressable `bool` framebuffer (not a page-byte stream) -
// every draw primitive in `gameCommon.cpp` (drawObject/drawBlock/
// drawObjectFill/etc) sets individual pixels directly, and the real
// SSD1306Brzo Arduino library only converts that into real hardware
// page-bytes internally, at the very end of each frame
// (`sendToScreen()`). Reproduced with the same `int[1024]` page-byte-
// laid-out framebuffer + `drvSetPixel`/`drvGetPixel` bit-op helpers this
// project's Gilbert-in-the-Downland/Tiny-Arena ports already established
// - every draw primitive here writes through those two helpers instead
// of touching `md_drawColumn()` directly, and `drvRenderFrame()` streams
// the finished buffer out once per real tick with no repacking needed
// (the layout already matches what `md_drawColumn()` expects).
//
// Not `tinyJoypadShim`/`obonoCoreShim` lineage - genuine bespoke ESP8266
// hardware (`SSD1306Brzo` + a 6-discrete-button analog-touch-pin scheme,
// `P1_Left/Top/Right/Bottom` + 2 more) - needed no new shim at all, since
// the button semantics map straight onto `isLeftPressed()`/
// `isRightPressed()`/`isUpPressed()`/`isDownPressed()`. Upstream's own
// real mapping is `P1_Top`=brake, `P1_Bottom`=accelerate (each also
// duplicated onto a P2 button this project's controller has no
// equivalent slot for, dropped as redundant) - ported as Up=brake,
// Down=accelerate, Left/Right=steer.
//
// A genuine attract/title screen was added (upstream has none at all -
// its own sketch just loops the flag-intro/scroll/drive/win-lose cycle
// forever with no explicit "press to start" gesture, looping straight
// back into the flag intro even after a loss) - matching this project's
// own near-universal convention of a real title screen gating a fresh
// Fire press before a game (re)starts, rather than auto-looping. Losing
// or fully winning both return here instead of upstream's own automatic
// restart, a deliberate, documented UX difference from a literal port.
//
// `fixpoint.h` was never needed - `driveGame.cpp` itself does no
// float/fixed-point math anywhere (only `rotateObject`, unused by this
// game, needs it) - and no audio-generation formula exists to derive
// either, since upstream's own `audioPlay("data/carStart.wav")` is real
// WAV playback (ESP8266Audio + I2S, `platform_audio_esp8266.cpp`), not a
// tone formula this project could re-derive the way Sound()-based
// hardware usually allows - approximated with a short representative
// two-tone "engine start" cue instead, the same "no exact real
// equivalent, use a representative substitute" precedent already used
// for Wren Rollercoaster's own beep()-formula guess.
//
// A genuine real-time throttle exists upstream (`updateMinTime(33)`,
// ~30fps) - matching the "genuine fixed real-rate" category from this
// project's own frame-pacing survey, not the "no timing model" one -
// reproduced with a real `DRV_TICK_DIVISOR=2` whole-tick throttle so
// every one of upstream's own per-tick physics constants (carSpeed
// deltas, distance-per-tick, turn-depth countdown) ports over completely
// unmodified, tick-for-tick, with no rescaling needed at all. Every
// `checkTime(seconds)`/`getElapsedSeconds()` real-millisecond check
// became a plain `drvStateTicks` frame counter compared against
// `seconds * DRV_FPS`, reset once on genuine state entry (matching
// upstream's own `scene != lastscene` one-shot-setup pattern) - the
// exact same real-world durations upstream intended, just measured in
// logic ticks instead of milliseconds.
//
// `drawScroller()`'s own real upstream bug was preserved faithfully, not
// "fixed": its trailing 3 extra draw calls read the *same* array index
// twice in a row (`scrollerText[i]` at y=0, then `scrollerText[i++]` at
// y=8 - i is not incremented between them) before finally drawing
// `scrollerText[i]` a third time at a fixed mid-screen position with
// backfill on. This means the scroller's own 8th text slot is drawn
// TWICE (identically, at two different fixed y positions) rather than
// showing two different trailing lines the way the 9-slot array might
// suggest - reproduced exactly via `drvDrawScrollerIntro`/
// `drvDrawScrollerOutro`, each inlining this same 7-scroll-plus-3-fixed
// draw shape with their own literal string content instead of taking a
// generic 2D string-array parameter (this dialect has no clean
// equivalent, and only 2 call sites ever existed anyway).
//
// Data tables (font + all 8 car/flag sprites) extracted via a Python
// script and byte-diff-verified against the real counts before ever
// building, matching this project's own established anti-transcription-
// error discipline.
//
// **CPU optimization pass, done proactively after shipping still read a
// saturated 100% via the WebGL perf overlay.** Every draw primitive
// initially routed through a single-pixel `drvSetPixel()` helper (the
// same shape as Gilbert in the Downland/Tiny Arena's own framebuffer
// helpers) - correct, but per this project's own repeatedly-confirmed
// lesson (raw per-call overhead dominates cost without v32opt's
// inlining, this build uses SKIP_V32OPT=1), far too many small calls for
// a game whose every screen is dense with drawn area. Fixed in two
// rounds, each measured before moving to the next rather than assumed:
// (1) inlined the page/bit bit-math directly into every draw primitive
// (`drvDrawBlock`/`drvDrawObjectFill`/`drvDrawObjectBF`/`drvDisplayNoise`/
// `drvDrawObjectWavy`/`drvDrawChar`), and replaced `drvDisplayClear()`'s
// own 8192-call-per-frame pixel loop with a flat 1024-word direct buffer
// fill - genuinely necessary since every state's own draw function
// starts with a full-screen clear; (2) even after that, the plain
// 3-line attract screen (no gameplay at all) still read 83% - traced to
// `drvDrawChar()` calling a separate `drvGetFontPixel()` function once
// per pixel (64 calls per character, each redundantly recomputing the
// glyph's own row/column offset via a division and a modulo that's
// genuinely constant for the whole character) - inlined that lookup
// directly into `drvDrawChar()` too, computing the glyph offset once per
// character instead of once per pixel. Measured via the perf overlay
// after each round: attract-screen CPU dropped 83%->62%, and real
// driving gameplay (previously an unmeasurable pegged 100%, indicating a
// real risk of frame truncation) dropped all the way to a comfortable
// 18%. The font-lookup inlining specifically turned out to be the larger
// win of the two, since text renders on every single screen in this
// game (attract/HUD/scrollers/level-slider/win-lose), not just the
// gameplay screen the first round of fixes targeted - a useful
// reminder that a "simple" screen with no game logic at all is still
// worth profiling, not just the busiest-looking one.
//
// **That 18% figure turned out to be a real but misleadingly optimistic
// single-frame sample, not representative of sustained play** - a direct
// user report of visible flickering during real gameplay led to an
// extended soak test (holding acceleration continuously, screenshotting
// every ~700ms) that caught an actually-truncated frame (only one road
// stripe drawn, HUD cut off mid-row) - this project's own well-documented
// "CPU exceeded budget, execution stopped mid-instruction-stream" failure
// signature, not just a high-but-safe percentage reading. Root-caused via
// the same "disable one candidate loop, re-run the exact same soak test"
// technique already established elsewhere in this project: the road's
// own "side of the road" checkered-background loop draws a full 128-wide
// strip for every one of its own ~30 rows, unconditionally, even though
// the road-scanning loop immediately afterward completely overdraws the
// center portion of nearly every one of those same rows anyway. Fixed by
// narrowing that loop to only draw the two side "shoulder" strips outside
// the road's own known reach at each row, computed with the exact same
// width/x formula the road-scanning loop itself uses (a literal
// duplicate of that math, not a guess) - safe because the road loop's own
// turnOffset value only ever decays toward 0 as y increases within a
// frame, so using this frame's un-decayed starting `drvTurnOffset` for
// the margin can only ever over-estimate the road's true reach (a
// slightly wider skipped margin than the strict minimum), never
// under-estimate it and leave a real gap in the background. Re-ran the
// identical soak test afterward: all 20 sampled frames (including the
// hardest visible case, a sharp turn with 2 cars on screen at once)
// rendered completely, with no further truncation observed - CPU still
// frequently reads a clamped 100% in these same samples, matching this
// project's own repeated finding that the perf overlay's 0-100 display
// can't distinguish "right at the ceiling" from "over it," but the
// concrete, visible symptom the user actually reported (flickering from
// real truncated frames) was confirmed gone via direct observation, not
// just inferred from a friendlier-looking number.

