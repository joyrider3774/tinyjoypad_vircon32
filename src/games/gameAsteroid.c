void astSpawnAsteroid( int slot, int size, float fixX, float fixY )
{
    astAstSpeed[ slot ] = arand( 10 ) / 10.0;
    astAstDirection[ slot ] = arand( 360 );
    astAstRotateAmount[ slot ] = 1 + arand( 4000 ); // clamped away from 0 - see header comment
    astAstSize[ slot ] = size;
    astAstFixX[ slot ] = fixX;
    astAstFixY[ slot ] = fixY;
    // Also set the integer render/collision position immediately - a
    // real bug found via direct user report ("splitting an asteroid...
    // pieces briefly drawn far away from original position"): this is a
    // fixed-size 90-slot pool reused across the whole session, so a
    // freshly-claimed slot's astAstX/astAstY still held whatever screen
    // position the slot's PREVIOUS occupant last had - astDisplayPlaying()
    // renders from astAstX/astAstY directly, and those only get
    // recomputed from astAstFixX/astAstFixY once a tick later inside
    // astUpdateAsteroidMovement() - so a new split-off asteroid rendered
    // at its stale predecessor's old position for exactly one frame
    // before snapping to the correct spot. Deriving them here too,
    // matching the exact same wrap formula astUpdateAsteroidMovement()
    // uses, closes that one-frame gap entirely.
    int fx = (int)fixX;
    int fy = (int)fixY;
    astAstX[ slot ] = fx % 128; if( astAstX[ slot ] < 0 ) astAstX[ slot ] = astAstX[ slot ] + 128;
    astAstY[ slot ] = fy % 64; if( astAstY[ slot ] < 0 ) astAstY[ slot ] = astAstY[ slot ] + 64;
}

