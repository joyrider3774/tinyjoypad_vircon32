// Asteroid (Tony M / "tonym128", GPLv3). A real Asteroids clone - rotate
// and thrust a ship, shoot rocks that split into smaller pieces, across
// 10 waves of increasing count, with an actual rotation-rendered ship
// and asteroid sprites (not just translated bitmaps - every sprite is
// re-rasterized every frame at its own current spin angle).
//
// Ported from `more games/ESP8266GameOn/myGame.cpp`/`.hpp` - the fourth
// port from tonym128's own ESP8266/SSD1306 game-framework family, after
// the `BFlight` bundle (Road Rush/DFlight/MRunnr) closed out. This is a
// genuinely different, OLDER repo (`ESP8266GameOn`, the predecessor
// tonym128's own README describes `BFlight` as the newer, consolidated
// successor to) - resolves this project's own long-standing open
// question about whether "game-asteroid" survived into `BFlight`'s own
// newer game list: it did not. `ESP8266GameOn`'s own README states
// directly "You can see the Asteroids demo on the master branch" - the
// repo's own generic "write your own game here" file (`myGame.cpp`/
// `.hpp`) currently holds the Asteroids demo, not a separate branch, so
// no further branch-fetching was needed - confirmed by reading the
// already-cloned master branch directly. Menu title "ASTEROID" (matching
// the repo's own scroller text, " -= Asteroid =- "), credited "TONYM128"/
// ESP8266, matching Road Rush/DFlight/MRunnr's own credit.
//
// Same `int[1024]` page-byte framebuffer layout as every other port in
// this project (`astFrameBuffer`) - upstream's own `ScreenBuff.
// consoleBuffer[8192]` is a full pixel-addressable `bool` array, real
// hardware page-bytes only produced at the very end of a frame. Every
// draw primitive writes directly into the framebuffer via inlined
// page/bit math from the start, `astDisplayClear()` is a flat 1024-word
// fill, and `astDrawChar()` inlines its own font lookup - all applying
// this project's own hard-won Road Rush lessons proactively rather than
// waiting for a CPU report, per standing instruction. Font data (a
// byte-for-byte match to Road Rush/DFlight/MRunnr's own already-
// verified `myfont.hpp` extraction, confirmed via a script diff before
// reuse rather than assumed from the shared filename) is copied
// verbatim, not retyped by hand - the exact discipline MRunnr's own port
// needed to *learn* the hard way (a hand-retyped copy of this same table
// was silently truncated there) is applied here from the very start.
//
// **A genuinely new rendering technique for this project**: every
// sprite (ship, all 3 asteroid sizes) is rendered via real per-pixel 2D
// image rotation (`astRotateObject()`, a direct port of upstream's own
// `rotateObject()`) - for each destination pixel, an inverse rotation
// matrix (real `sin()`/`cos()`, not the fixed-point polynomial
// approximation upstream's own `fixpoint.h` provides for non-Emscripten
// targets, matching Tiny Arena's/MRunnr's own "Vircon32 has real
// hardware floats, fixpoint.h is unnecessary" precedent) locates the
// corresponding source pixel and nearest-neighbor-samples it, writing 0
// for anything that lands outside the source bitmap. `FIXP_INT_PART`'s
// own right-shift (floor, not truncate-toward-zero, for a value that
// can be genuinely negative) is reproduced with a real `floor()` call
// rather than a plain `(int)` truncating cast, matching this project's
// own established FIXP_INT_PART-to-floor() translation used throughout
// MRunnr.
//
// **Two independent angle fields, ported as two independent fields, not
// collapsed into one**: `direction` (fixed at spawn for an asteroid,
// continuously player-steered for the ship - degrees, 0-360) drives
// *movement* via `xVec()`/`yVec()`; `rotation` (continuously increasing
// over time, an entirely separate value) drives *rendering* via
// `astRotateObject()`. These were never the same value upstream and stay
// that way here.
//
// **`xVec()`/`yVec()` are a deliberate piecewise-linear approximation of
// a circle (a diamond/rhombus direction shape), not real trigonometry -
// preserved exactly, not "upgraded" to real sin()/cos() calls** despite
// Vircon32 having real hardware trig available (and despite this same
// file using real trig for sprite *rotation* just above). Traced through
// by hand to confirm this is a deliberate, working design (linear
// interpolation between the four axis-aligned directions, scaled by
// `direction/90`), not broken/dead code - the same "preserve a real,
// functioning, if unusual, design choice" precedent already applied
// throughout this project rather than silently "improving" it into
// something upstream never actually shipped.
//
// The player's own `rotation` field is itself a deliberate approximation
// too: clamped to `[0, 6]` (not `[0, 2*pi≈6.283]`) via an explicit bound
// check on each increment/decrement rather than a true modulo - close
// enough to a full turn that the visible seam is not perceptible -
// ported exactly as upstream has it, not "corrected" to a real 2*pi wrap.
//
// Every genuine real-millisecond gate (`player1.firetimeout`/
// `FIREPACING`, `scoreTimeMultiplier`/`SCORETIMEMULTTIMEOUT`, each
// asteroid's own continuously-growing `rotation = getTimeInMillis() /
// rotateAmount`) was converted to a frame-tick equivalent, matching the
// same `checkTime()`/`getElapsedSeconds()`-to-tick-counter conversion
// already established for Road Rush/DFlight/MRunnr - this repo shares
// the exact same real `updateMinTime(33)` (~30fps) outer-loop cap
// (confirmed directly in this repo's own `game.cpp`, not assumed from
// the sibling repos), so the same `AST_TICK_DIVISOR = 60/30` whole-tick
// throttle applies here too. `fire[i].life -= getCurrentFPS();` (life
// decremented by the *measured* current frame rate each tick, not a
// fixed constant) becomes a decrement by the fixed `AST_FPS` constant
// instead, since this port has no equivalent "measured" FPS value and
// the fixed rate is already what upstream's own moving-average FPS
// counter would settle on in steady state anyway.
//
// Not `tinyJoypadShim`/`obonoCoreShim` lineage - the same bespoke
// ESP8266 hardware/button scheme as every other tonym128 port in this
// project (`P1_Top/Bottom/Left/Right` + `P2_Left/Right`), needing no new
// shim. Up/Down = thrust/unused (upstream reads `p1keys.up` for thrust
// but never binds a real "down" action - confirmed dead by grep before
// leaving it unwired), Left/Right = rotate, and *both* `P2_Right` (`a`,
// fire) and `P2_Left` (`b`, upstream's own secondary thrust alias) are
// real, live inputs here - mapped onto `isFirePressed()`/
// `isFire2Pressed()` respectively (the same `isFire2Pressed()` primitive
// Tiny Minez's own B-button flag-toggle gesture already proved out).
// `P2_Top` (upstream's own "abandon and restart" gesture) is dead here
// too, matching every other tonym128 port's own precedent of not
// duplicating this cartridge's existing Start-button quit dialog.
//
// `Alien10x10` (declared in `myGame.hpp`, a 10x10 alien-ship sprite) is
// confirmed dead by grep - never referenced anywhere in `myGame.cpp`'s
// own logic - dropped rather than ported, matching this project's
// standing "confirm dead code via grep before dropping it" discipline.
//
// A genuine, load-bearing upstream quirk, preserved rather than "fixed":
// `initAttractMode()` (spawning 2-9 random demo asteroids for the
// attract screen) does *not* zero the whole 90-slot asteroid array
// first, unlike `startLevel()`'s own explicit full-array clear - it
// only ever touches indices `0` through its own randomly-chosen count.
// This means the attract screen can, in principle, show a few leftover
// asteroids from whatever session state preceded it (most visibly after
// a loss, since a game-over never clears the array either) layered on
// top of the fresh demo set - a real, if minor, upstream quirk (not a
// crash risk, just a potentially busier-than-intended attract-screen
// asteroid field) ported exactly as observed rather than adding a clear
// upstream itself doesn't perform.

