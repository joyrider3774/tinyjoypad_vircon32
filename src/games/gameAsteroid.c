void astBeginLoad( void )
{
    astLoadHoldTicks = 0;
    astDisplayClear( 0 );
    astDrawObject( 0, 0, 128, 64, astLogoImage );
    astState = AST_STATE_LOAD;
}

void astBeginAttract( void )
{
    astFrameCounter = 0;
    astInitAttractMode();
    astState = AST_STATE_ATTRACT;
}

void astBeginIntroScroll( void )
{
    astFrameCounter = 0;
    astResetGameState();
    astState = AST_STATE_INTRO_SCROLL;
}

void astBeginLevelSlider( void )
{
    astFrameCounter = 0;
    astState = AST_STATE_LEVEL_SLIDER;
}

void astBeginPlay( void )
{
    if( astLevel == 1 )
    {
        astResetGameState();
        astStartLevel();
    }
    astState = AST_STATE_PLAY;
}

void astBeginOutroScroll( void )
{
    astFrameCounter = 0;
    astState = AST_STATE_OUTRO_SCROLL;
}

// -----------------------------------------------------------------------------
// Per-tick state dispatch
// -----------------------------------------------------------------------------

void astUpdateLoad( void )
{
    astLoadHoldTicks = astLoadHoldTicks + 1;
    if( astLoadHoldTicks > AST_FPS * 2 ) astBeginAttract(); // 2000ms hold, matching updateMinTime(2000)
}

void astUpdateAttract( void )
{
    if( astFireEdge || astFire2Edge ) { astBeginIntroScroll(); return; }
    astUpdateAttractMode();
    astDisplayAttractMode();
}

void astUpdateIntroScroll( void )
{
    astFrameCounter = astFrameCounter + 1;
    if( !astDrawScrollerIntro() ) astBeginLevelSlider();
}

void astUpdatePlay( void )
{
    if( astWin )
    {
        astWin = 0;
        if( astLevel >= 10 ) astBeginOutroScroll();
        else
        {
            astStartLevel();
            astBeginLevelSlider();
        }
        return;
    }
    astUpdatePlaying();
    astDisplayPlaying();
}

void astUpdateOutroScroll( void )
{
    astFrameCounter = astFrameCounter + 1;
    if( !astDrawScrollerOutro() )
    {
        astWin = 0;
        astBeginAttract();
    }
}

void astUpdateGameOver( void )
{
    // Deliberately does NOT clear the framebuffer - upstream's own
    // scene-5 body never does either, so the frame frozen at the exact
    // moment of collision (the last real astDisplayPlaying() call, still
    // sitting in astFrameBuffer) stays visible underneath the "Game
    // Over" text and sliders drawn on top of it.
    astFrameCounter = astFrameCounter + 1;
    astDrawGameOver();
    if( astFrameCounter > 100 ) astBeginAttract();
}

void astUpdateLevelSlider( void )
{
    astFrameCounter = astFrameCounter + 1;
    astDrawLevelSlider();
    if( astFrameCounter > 100 ) astBeginPlay();
}

