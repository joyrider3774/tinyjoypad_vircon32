// A real, if small, "text/UI screen" optimization found via direct user
// request to check text rendering: upstream's own loop counts `i` down
// from frameCounter to 1, only ever drawing on the *first* 64
// iterations (a `counter<64` guard) - but the loop itself keeps running
// for every remaining iteration regardless, just re-checking a guard
// that can now never pass again. This is a genuine sliding *window*
// effect (the drawn `i` range shifts upward as frameCounter grows, not a
// fixed fill-up), so the fix has to preserve that exact window - not
// simply cap the loop at 64 - by computing the window's own bounds
// directly instead of decrementing down to it from frameCounter every
// single call.
void astDrawSliderBars( void )
{
    int i, lo;
    lo = astFrameCounter - 63;
    if( lo < 1 ) lo = 1;
    for( i = lo; i <= astFrameCounter; i++ )
    {
        astSetRawPixel( 128 * 20 + i, 1 );
        astSetRawPixel( 128 * 35 - i, 1 );
    }
}

