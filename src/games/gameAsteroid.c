void astRenderFrame( void )
{
    md_beginFrame();
    int col, page;
    for( page = 0; page < 8; page++ )
      for( col = 0; col < 128; col++ )
        md_drawColumn( col, page, astFrameBuffer[ col + ( page * 128 ) ] );
}

void gameAsteroid_init( void )
{
    InitTinyJoypad();
    astTickSkipCounter = 0;
    astPrevFire = 0;
    astFireEdge = 0;
    astPrevFire2 = 0;
    astFire2Edge = 0;
    astHiScore = 0;
    astLastScore = 0;
    astMultiplier = 1;
    astMaxMultiplier = 5;
    astScoreMultTimer = 0;
    astFireCooldownTicks = 0;
    astClearAllAsteroids();
    astBeginLoad();
}

void gameAsteroid_update( void )
{
    astTickSkipCounter = astTickSkipCounter + 1;
    if( astTickSkipCounter < AST_TICK_DIVISOR ) return;
    astTickSkipCounter = 0;

    int fireNow = isFirePressed();
    astFireEdge = fireNow && !astPrevFire;
    astPrevFire = fireNow;

    int fire2Now = isFire2Pressed();
    astFire2Edge = fire2Now && !astPrevFire2;
    astPrevFire2 = fire2Now;

    astKeyUp = isUpPressed();
    astKeyDown = isDownPressed();
    astKeyLeft = isLeftPressed();
    astKeyRight = isRightPressed();
    astKeyA = isFirePressed();
    astKeyB = isFire2Pressed();

    if( astState == AST_STATE_LOAD ) astUpdateLoad();
    else if( astState == AST_STATE_ATTRACT ) astUpdateAttract();
    else if( astState == AST_STATE_INTRO_SCROLL ) astUpdateIntroScroll();
    else if( astState == AST_STATE_PLAY ) astUpdatePlay();
    else if( astState == AST_STATE_OUTRO_SCROLL ) astUpdateOutroScroll();
    else if( astState == AST_STATE_GAME_OVER ) astUpdateGameOver();
    else astUpdateLevelSlider();

    astRenderFrame();
}

void gameAsteroid_forceRedraw( void )
{
    if( astState == AST_STATE_LOAD ) { astDisplayClear( 0 ); astDrawObject( 0, 0, 128, 64, astLogoImage ); }
    else if( astState == AST_STATE_ATTRACT ) astDisplayAttractMode();
    else if( astState == AST_STATE_INTRO_SCROLL ) astDrawScrollerIntro();
    else if( astState == AST_STATE_PLAY ) astDisplayPlaying();
    else if( astState == AST_STATE_OUTRO_SCROLL ) astDrawScrollerOutro();
    else if( astState == AST_STATE_GAME_OVER ) astDrawGameOver(); // no clear - see astUpdateGameOver()'s own comment
    else astDrawLevelSlider();
    astRenderFrame();
}
