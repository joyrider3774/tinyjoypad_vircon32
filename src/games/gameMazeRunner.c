void mzRotate( float rs )
{
    float oldDirX = mzDirX;
    mzDirX = mzDirX * cos( rs ) - mzDirY * sin( rs );
    mzDirY = oldDirX * sin( rs ) + mzDirY * cos( rs );
    float oldPlaneX = mzPlaneX;
    mzPlaneX = mzPlaneX * cos( rs ) - mzPlaneY * sin( rs );
    mzPlaneY = oldPlaneX * sin( rs ) + mzPlaneY * cos( rs );
}

void mzBeginPlaying( void )
{
    mzStateTicks = 0;
    mzWin = 0;
    mzEndSeconds = 0;
    mzState = MZ_STATE_PLAY;
}

void mzUpdatePlaying( void )
{
    mzStateTicks = mzStateTicks + 1;

    // Win check - "win is in the top left" per upstream's own comment;
    // note this compares a signed difference against 1.5, not its
    // absolute value, matching upstream exactly rather than "fixing" it
    // into a symmetric distance check.
    if( !mzWin )
    {
        mzWin = ( mzPosX - MZ_END_X < 1.5 ) && ( mzPosY - MZ_END_Y < 1.5 );
    }
    else
    {
        if( mzEndSeconds == 0 ) mzEndSeconds = mzGetElapsedSeconds();
        else if( mzGetElapsedSeconds() - mzEndSeconds > 0 )
        {
            mzFrameCounter = 0;
            mzState = MZ_STATE_WIN_SCROLL;
            return;
        }
    }

    if( mzGetElapsedSeconds() >= MZ_STAGE_TIME_SECONDS )
    {
        // Time's up - stop updating movement, matching upstream's own
        // early "return false" here.
        mzWin = 0;
        if( mzEndSeconds == 0 ) mzEndSeconds = mzGetElapsedSeconds();
        else if( mzGetElapsedSeconds() - mzEndSeconds > 0 )
        {
            mzFrameCounter = 0;
            mzState = MZ_STATE_LOSE_SCROLL;
        }
        return;
    }

    mzTraversal[ (int)mzPosX + (int)mzPosY * MZ_MAP_SIZE ] = 1;

    float moveSpeed = 0.1;
    float rotSpeed = 0.05;

    if( mzKeyUp )
    {
        if( mzWorld[ (int)( mzPosX + mzDirX * moveSpeed ) + (int)mzPosY * MZ_MAP_SIZE ] == 0 )
          mzPosX = mzPosX + mzDirX * moveSpeed;
        if( mzWorld[ (int)mzPosX + (int)( mzPosY + mzDirY * moveSpeed ) * MZ_MAP_SIZE ] == 0 )
          mzPosY = mzPosY + mzDirY * moveSpeed;
        // No exact upstream WAV formula to derive from (audioPlay() is
        // real sample playback, not a tone formula) - a short
        // representative footstep blip instead, same "no exact
        // equivalent, use a representative substitute" precedent as
        // Road Rush's own engine-start cue/Wren Rollercoaster's beep().
        Sound( 150, 2 );
    }
    if( mzKeyDown )
    {
        if( mzWorld[ (int)( mzPosX - mzDirX * moveSpeed ) + (int)mzPosY * MZ_MAP_SIZE ] == 0 )
          mzPosX = mzPosX - mzDirX * moveSpeed;
        if( mzWorld[ (int)mzPosX + (int)( mzPosY - mzDirY * moveSpeed ) * MZ_MAP_SIZE ] == 0 )
          mzPosY = mzPosY - mzDirY * moveSpeed;
        Sound( 150, 2 );
    }
    if( mzKeyRight ) mzRotate( -rotSpeed );
    if( mzKeyLeft ) mzRotate( rotSpeed );
}

// Resolves which 64x64 texture a wall pattern samples from - matching
// upstream's own `pattern < 5` (ordinary walls, start marker) vs
// `pattern >= 5` (the win/exit marker) dispatch. A function-with-early-
// return, not a ternary (unsupported by this dialect) - same shape as
// Tiny Dungeon's own tdngResolveBitmapArray().
int* mzResolveTexture( int pattern )
{
    if( pattern < 5 ) return mzWallImage;
    return mzDefconImage;
}

void mzDisplayPlaying( void )
{
    mzDisplayClear( 0 );

    // Floor is now filled per-column, right after each column's own
    // drawEnd is known (below) - not upfront as a fixed 128x32 block.
    // Direct user report: CPU pegs at 100% specifically when turning
    // close to a wall - exactly the case where the wall stripe's own
    // drawEnd reaches all the way to row 63, meaning the *entire* floor
    // portion of that column was being filled here and then immediately,
    // 100% wastefully, overdrawn by the wall texture pass a few lines
    // later. Same "don't draw a whole strip that's about to be
    // completely overdrawn anyway" lesson as Road Rush's own road-
    // shoulder fix - just discovered per-column instead of per-row.

    // Hoisted out of the per-column loop, applied proactively (not
    // waiting for a CPU report) per this project's own established
    // "don't recompute a frame-constant value once per column/pixel"
    // lesson (Bat Bonanza's own attract-screen strlen() fix, Road Rush's
    // ball-position division, etc): mzPosX/mzPosY don't change anywhere
    // during this whole render pass, so floor() only needs to run once,
    // not once per column.
    float startMapX = floor( mzPosX );
    float startMapY = floor( mzPosY );

    int x;
    for( x = 0; x < 128; x++ )
    {
        float fmapX = startMapX;
        float fmapY = startMapY;

        // mzCameraX[x] (precomputed once at init, see gameMazeRunner_init())
        // replaces a fresh 2.0*x/128.0-1.0 division every column - it's a
        // pure function of x, never of player state, so it can never
        // change between frames either.
        float fcameraX = mzCameraX[ x ];
        float frayDirX = mzDirX + mzPlaneX * fcameraX;
        float frayDirY = mzDirY + mzPlaneY * fcameraX;

        float fdeltaDistX, fdeltaDistY;
        if( frayDirX == 0 ) fdeltaDistX = 1000000.0; else fdeltaDistX = fabs( 1.0 / frayDirX );
        if( frayDirY == 0 ) fdeltaDistY = 1000000.0; else fdeltaDistY = fabs( 1.0 / frayDirY );

        float fperpWallDist;
        int stepX, stepY;
        int hit, side;
        float fsideDistX, fsideDistY;

        if( frayDirX < 0 ) { stepX = -1; fsideDistX = ( mzPosX - fmapX ) * fdeltaDistX; }
        else { stepX = 1; fsideDistX = ( fmapX + 1.0 - mzPosX ) * fdeltaDistX; }
        if( frayDirY < 0 ) { stepY = -1; fsideDistY = ( mzPosY - fmapY ) * fdeltaDistY; }
        else { stepY = 1; fsideDistY = ( fmapY + 1.0 - mzPosY ) * fdeltaDistY; }

        hit = 0;
        side = 0;
        while( !hit )
        {
            if( fsideDistX < fsideDistY )
            {
                fsideDistX = fsideDistX + fdeltaDistX;
                fmapX = fmapX + stepX;
                side = 0;
            }
            else
            {
                fsideDistY = fsideDistY + fdeltaDistY;
                fmapY = fmapY + stepY;
                side = 1;
            }
            if( mzWorld[ (int)fmapX + (int)fmapY * MZ_MAP_SIZE ] > 0 ) hit = 1;
        }

        if( side == 0 )
        {
            if( frayDirX == 0 ) fperpWallDist = 1000000.0;
            else fperpWallDist = ( fmapX - mzPosX + ( 1 - stepX ) / 2.0 ) / frayDirX;
        }
        else
        {
            if( frayDirY == 0 ) fperpWallDist = 1000000.0;
            else fperpWallDist = ( fmapY - mzPosY + ( 1 - stepY ) / 2.0 ) / frayDirY;
        }

        int lineHeight;
        if( fperpWallDist == 0 ) lineHeight = 1000000; else lineHeight = (int)( 64.0 / fperpWallDist );

        int drawStart = -lineHeight / 2 + 32;
        if( drawStart < 0 ) drawStart = 0;
        int drawEnd = lineHeight / 2 + 32;
        if( drawEnd >= 64 ) drawEnd = 63;

        // Per-column floor fill, narrowed to exactly the rows the wall
        // stripe below won't already overdraw (see this function's own
        // header comment). x==0 is skipped, faithfully matching
        // mzDrawBlock()'s own preserved column-0 exclusion quirk (the
        // original full-width call this replaced was itself gated by
        // that same check).
        if( x > 0 )
        {
            int floorStart = drawEnd;
            if( floorStart < 32 ) floorStart = 32;
            int fy, fidx, fbit;
            for( fy = floorStart; fy < 64; fy++ )
            {
                fidx = x + ( ( fy >> 3 ) * 128 );
                fbit = 1 << ( fy & 7 );
                mzFrameBuffer[ fidx ] = mzFrameBuffer[ fidx ] | fbit;
            }
        }

        int pattern = mzWorld[ (int)fmapX + (int)fmapY * MZ_MAP_SIZE ] - 1;

        float fwallX;
        if( side == 0 ) fwallX = fperpWallDist * frayDirY + mzPosY;
        else fwallX = fperpWallDist * frayDirX + mzPosX;
        fwallX = fwallX - floor( fwallX ); // frac(), matching FIXP_DEC_PART's own two's-complement-correct semantics

        int* tex = mzResolveTexture( pattern );
        int texSize = 64;

        int ftexX = (int)( fwallX * texSize );
        // Defensive clamp beyond a literal translation - a genuine
        // out-of-bounds array read risk on Vircon32 (unlike real AVR
        // flash, which upstream never guarded against either) if
        // floating-point rounding ever pushes fwallX to exactly 1.0.
        if( ftexX < 0 ) ftexX = 0;
        if( ftexX >= texSize ) ftexX = texSize - 1;
        if( side == 0 && frayDirX > 0 ) ftexX = texSize - 1 - ftexX;
        if( side == 1 && frayDirY < 0 ) ftexX = texSize - 1 - ftexX;

        if( lineHeight > 0 )
        {
            // Incremental texY (replaces upstream's own per-row double-
            // division "flat" formula) - see header comment for the
            // full derivation/equivalence argument.
            float step = ( 1.0 * texSize ) / lineHeight;
            float texPos = ( drawStart - 32 + lineHeight / 2.0 ) * step;

            int y, texY, idx, bit, color;
            // idx/bit tracked incrementally instead of recomputed from
            // scratch (a multiply + a shift) every single row - bit is
            // just shifted left each row, only rolling over into the
            // next page's idx once every 8 rows, applying the same
            // "don't redo per-row work that's mostly constant across a
            // small run" lesson already used throughout this project
            // (Tiny Doc's row-scoped dirty cache, etc), just at row
            // granularity instead of frame granularity.
            idx = x + ( ( drawStart >> 3 ) * 128 );
            bit = 1 << ( drawStart & 7 );
            for( y = drawStart; y < drawEnd; y++ )
            {
                texY = (int)texPos;
                if( texY < 0 ) texY = 0;
                if( texY >= texSize ) texY = texSize - 1;
                color = tex[ ftexX + ( texY << 6 ) ]; // texSize==64==2^6, multiply-by-constant replaced with a shift

                // Inlined pixel write (matches Tiny Arena's own inlined
                // arVBuf() precedent - a per-column, per-row hot loop
                // like this one pays real per-call overhead for a
                // separate mzSetPixel() function, not worth it here).
                if( color ) mzFrameBuffer[ idx ] = mzFrameBuffer[ idx ] | bit;
                else mzFrameBuffer[ idx ] = mzFrameBuffer[ idx ] & ( 0xFF - bit );

                texPos = texPos + step;
                bit = bit << 1;
                if( bit > 0xFF ) { bit = 1; idx = idx + 128; }
            }
        }
    }

    // Progress bar
    int seconds = mzGetElapsedSeconds();
    int percTimeLeft = 128 - seconds * 128 / MZ_STAGE_TIME_SECONDS;
    mzDrawBlock( 0, 0, percTimeLeft, 5, 1 );

    // Win / Game Over text - upstream's own char fps[30] buffer was
    // never initialized (its own sprintf() call is commented out), so
    // strlen(fps) read genuinely undefined memory - clearly broken, dead
    // code, not a deliberate quirk with an observable intended result.
    // The commented-out sprintf() calls make the *intended* text
    // unambiguous, so this restores it directly instead of reproducing
    // garbage (see header comment).
    if( mzWin )
    {
        mzDrawString( "YOU WIN!", 32, 30, 0 );
    }
    else if( mzGetElapsedSeconds() > MZ_STAGE_TIME_SECONDS )
    {
        mzDrawString( "GAME OVER!", 24, 30, 0 );
    }

    // Minimap - a temp copy of the persistent traversal grid, with a
    // transient (non-persisted) 3x3 "currently near" reveal window
    // overlaid on top, matching upstream's own traverseMap[] shape
    // exactly.
    int i, j;
    for( i = 0; i < MZ_MAP_SIZE * MZ_MAP_SIZE; i++ ) mzMinimapBuf[ i ] = mzTraversal[ i ];

    // Upstream's own `int mapX = int(posX)` casts the raw FIXPOINT
    // (a scaled int32_t) directly to int with no FIXP_TO_INT unscale -
    // every other position read in this whole file goes through that
    // unscale, so this looks like a genuine upstream typo/omission
    // rather than a deliberate choice: on real hardware it leaves mapX
    // in the hundreds-of-thousands range, so the bounds check below
    // (`(mapX+i) > 0 && < mapWidth`) can never pass and this whole 3x3
    // "reveal the area right around the player" window silently never
    // activates. Since this port's own mzPosX/mzPosY were never fixed-
    // point-scaled to begin with (see header comment on the float
    // conversion), a plain (int) cast here is simply correct - it can't
    // reproduce a bug that was purely an artifact of upstream's own
    // fixed-point representation, so the reveal window works as
    // evidently intended instead.
    int mapX = (int)mzPosX;
    int mapY = (int)mzPosY;
    for( i = -1; i <= 1; i++ )
      for( j = -1; j <= 1; j++ )
        if( ( mapX + i ) > 0 && ( mapX + i ) < MZ_MAP_SIZE && ( mapY + j ) > 0 && ( mapY + j ) < MZ_MAP_SIZE )
          mzMinimapBuf[ ( mapX + i ) + ( mapY + j ) * MZ_MAP_SIZE ] = 1;

    mzDrawObject( 128 - MZ_MAP_SIZE - 1, 64 - MZ_MAP_SIZE - 1, MZ_MAP_SIZE, MZ_MAP_SIZE, mzMinimapBuf );
}

// -----------------------------------------------------------------------------
// State setup / transitions (mirrors mazeRunnerLoop()'s own switch,
// minus upstream's own unreachable-from-here case 4 "done and exit" -
// this cartridge has no next mini-game to hand off to, matching Road
// Rush/DFlight's own precedent of returning to a fresh attract screen
// instead).
// -----------------------------------------------------------------------------

void mzBeginAttract( void )
{
    mzState = MZ_STATE_ATTRACT;
}

void mzBeginIntroScroll( void )
{
    mzMazeRunnerInit();
    mzFrameCounter = 0;
    mzState = MZ_STATE_INTRO_SCROLL;
}

void mzBeginLevelBars( void )
{
    mzFrameCounter = 0;
    mzState = MZ_STATE_LEVEL_BARS;
}

void mzUpdateAttract( void )
{
    mzDrawAttract();
    if( mzFireEdge ) mzBeginIntroScroll();
}

void mzUpdateIntroScroll( void )
{
    mzFrameCounter = mzFrameCounter + 1;
    if( !mzDrawScrollerIntro() ) mzBeginLevelBars();
}

void mzUpdateLevelBars( void )
{
    mzFrameCounter = mzFrameCounter + 1;
    mzDrawLevelBars();
    if( mzFrameCounter > 120 ) mzBeginPlaying();
}

void mzUpdatePlay( void )
{
    mzUpdatePlaying();
    mzDisplayPlaying();
}

void mzUpdateWinScroll( void )
{
    mzFrameCounter = mzFrameCounter + 1;
    if( !mzDrawScrollerWin() ) mzBeginAttract();
}

void mzUpdateLoseScroll( void )
{
    mzFrameCounter = mzFrameCounter + 1;
    if( !mzDrawScrollerLose() ) mzBeginIntroScroll();
}

// -----------------------------------------------------------------------------
// Entry points
// -----------------------------------------------------------------------------

void mzRenderFrame( void )
{
    md_beginFrame();
    int col, page;
    for( page = 0; page < 8; page++ )
      for( col = 0; col < 128; col++ )
        md_drawColumn( col, page, mzFrameBuffer[ col + ( page * 128 ) ] );
}

void gameMazeRunner_init( void )
{
    InitTinyJoypad();
    mzState = MZ_STATE_ATTRACT;
    mzTickSkipCounter = 0;
    mzPrevFire = 0;
    mzFireEdge = 0;

    int x;
    for( x = 0; x < 128; x++ ) mzCameraX[ x ] = 2.0 * x / 128.0 - 1.0;

    mzDisplayClear( 0 );
}

void gameMazeRunner_update( void )
{
    mzTickSkipCounter = mzTickSkipCounter + 1;
    if( mzTickSkipCounter < MZ_TICK_DIVISOR ) return;
    mzTickSkipCounter = 0;

    int fireNow = isFirePressed();
    mzFireEdge = fireNow && !mzPrevFire;
    mzPrevFire = fireNow;

    mzKeyUp = isUpPressed();
    mzKeyDown = isDownPressed();
    mzKeyLeft = isLeftPressed();
    mzKeyRight = isRightPressed();

    if( mzState == MZ_STATE_ATTRACT ) mzUpdateAttract();
    else if( mzState == MZ_STATE_INTRO_SCROLL ) mzUpdateIntroScroll();
    else if( mzState == MZ_STATE_LEVEL_BARS ) mzUpdateLevelBars();
    else if( mzState == MZ_STATE_PLAY ) mzUpdatePlay();
    else if( mzState == MZ_STATE_WIN_SCROLL ) mzUpdateWinScroll();
    else mzUpdateLoseScroll();

    mzRenderFrame();
}

void gameMazeRunner_forceRedraw( void )
{
    if( mzState == MZ_STATE_ATTRACT ) mzDrawAttract();
    else if( mzState == MZ_STATE_INTRO_SCROLL ) mzDrawScrollerIntro();
    else if( mzState == MZ_STATE_LEVEL_BARS ) mzDrawLevelBars();
    else if( mzState == MZ_STATE_PLAY ) mzDisplayPlaying();
    else if( mzState == MZ_STATE_WIN_SCROLL ) mzDrawScrollerWin();
    else mzDrawScrollerLose();
    mzRenderFrame();
}
