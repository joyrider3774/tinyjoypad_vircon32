// MRUNNR (Tony M / "tonym128", GPLv3). A real texture-mapped first-person
// maze crawler - rotate/move through a freshly-generated 25x25 maze
// with a real DDA raycaster (not a dithered approximation), racing a
// countdown timer to reach a marked exit before time runs out.
//
// Ported from `more games/BFlight/mazeRunner.cpp`/`.hpp` +
// `mazeGenerator.cpp`/`.hpp` - the third and last real game pulled from
// tonym128's own "BFlight" bundle (after Road Rush/driveGame and
// DFlight/bsideFly - see this project's CLAUDE.md "sixth beyond-scope
// discovery pass" section for how the whole bundle was found). This
// closes out the bundle entirely - the remaining files (`plasma`,
// `rotoZoomer`, `voxel`) are all procedural per-pixel effects with no
// discrete objects to port, out of scope per this project's GPU model
// (`rotoZoomer.hpp`'s own `defcon_image` texture data is reused here
// below, but its actual rotozoomer *effect* code is not).
//
// Menu title "MRUNNR", lifted directly from the intro scroller's own
// credit line (" -= mRunnr =-  "), the same "read the game's own
// on-screen text for its real name" approach already used for Road
// Rush/DFlight/Bat Bonanza/Falling Blocks. Credited "TONYM128" and MCU
// "ESP8266", matching Road Rush/DFlight's own credit (same repo/author/
// hardware, not re-derived).
//
// Same `int[1024]` page-byte framebuffer layout as Road Rush/DFlight/
// Gilbert in the Downland/Tiny Arena - upstream's own
// `ScreenBuff.consoleBuffer[8192]` is a full pixel-addressable `bool`
// array, converted to real hardware page-bytes only at the very end of
// a frame by the real SSD1306Brzo library. Every optimization lesson
// from Road Rush/DFlight applied here from the very start (per direct
// user instruction to apply them proactively, not retrofit them): every
// draw primitive writes directly into the framebuffer via inlined
// page/bit math, `mzDisplayClear()` is a flat 1024-word buffer fill, and
// `mzDrawChar()` inlines its own font lookup with hoisted per-row
// constants.
//
// Not `tinyJoypadShim`/`obonoCoreShim` lineage - genuine bespoke ESP8266
// hardware, the same `P1_Top/Bottom/Left/Right` mapping as Road Rush/
// DFlight, needing no new shim: Up/Down move forward/back, Left/Right
// rotate. `P2_Left` ("open", confirmed dead by grep - read into
// `Player1Keys.open` but never consulted anywhere else in the real game
// logic) and `P2_Top` (upstream's own "abandon and restart" gesture,
// dead here too - this cartridge already has its own Start-button quit-
// confirmation dialog, matching Road Rush/DFlight's own precedent of not
// wiring a redundant upstream restart gesture) are both left unwired.
//
// **Plain floats replace all of upstream's own `FIXPOINT` fixed-point
// emulation** (`fixpoint.h`, a 32.16 fixed-point format built entirely
// to avoid float math on the original ESP8266 target) - Vircon32 has
// real hardware float support, already proven by Tiny Arena's own
// working float-based raycaster, so there is nothing for the fixed-point
// layer to buy here. `FIXP_MULT`/`FIXP_DIV` become plain `*`/`/`;
// `FIXP_FIXP_INT_PART` (masks off the fractional bits, keeping the
// result in fixed-point units) becomes `floorf()`; `FIXP_DEC_PART`
// (masks to just the low 16 bits - a genuine two's-complement `frac()`
// that stays correct even for a negative fixed-point value) becomes
// `x - floorf(x)` rather than a naive truncating subtraction, matching
// the same semantics exactly. `FIXPOINT_SIN`/`FIXPOINT_COS` (a lossy
// fixed-point polynomial approximation, upstream's own comment: "the
// loss of precision is extraordinary!") become real `sin()`/`cos()`
// calls - already proven safe and available in this dialect by
// HollowSeeker/Wren Rollercoaster.
//
// **A real, deliberate array-indexing unification, chosen to eliminate
// a whole class of transpose bugs before ever writing the raycaster
// itself.** Upstream's own `Maze` class stores its internal maze as a
// flat `maze[y*WIDTH+x]` (a real coordinate-pair index, not a bug - `x`
// and `y` are just written in that order), while the *separate*
// `worldMap[WIDTH][HEIGHT]` the raycaster actually reads is a genuine C
// 2D array accessed as `worldMap[x][y]`, whose own real row-major memory
// layout is `x*HEIGHT+y` - a genuinely different linear formula from
// `maze[]`'s own `y*WIDTH+x`, needing upstream's own `copyMaze()` to
// swap x/y while copying. This port uses **one single convention for
// every maze-shaped array in the whole file** - `mzGen[x+y*25]` and
// `mzWorld[x+y*25]` (and `mzTraversal[x+y*25]`), all meaning "cell at
// column x, row y" - which happens to match upstream's own internal
// `maze[]` layout exactly (`y*WIDTH+x` and `x+y*25` are the same
// formula, WIDTH==25), so `mzGenerateMaze()`/`mzCarveMaze()` port over
// with no reindexing at all, and `mzCopyMazeToWorld()` becomes a
// trivial direct 625-word loop copy with zero transpose risk, instead
// of upstream's own swapped-index assignment.
//
// **Two genuine `checkTime(seconds)`/`getElapsedSeconds()` real-
// millisecond checks** (the play-state countdown, and the win/lose
// "hang for a beat before transitioning" pause) became a plain
// `mzStateTicks` frame counter compared against `seconds * MZ_FPS`,
// reset once on genuine state entry - the same conversion already
// established for Road Rush's own identical timer shape.
//
// **The uninitialized win/lose text buffer** - upstream's own
// `char fps[30];` followed by a *commented-out*
// `//sprintf(fps, "YOU WIN!");` and then `strlen(fps)` read on the never-
// initialized buffer - is clearly broken, dead code (undefined behavior
// even on real hardware, not a deliberate quirk with an observable
// intended result to preserve). The commented-out `sprintf` calls make
// the *intended* text unambiguous, so this port restores the real,
// obviously-intended "YOU WIN!"/"GAME OVER!" strings at the exact same
// positions instead of reproducing garbage - the same "fix clearly-
// broken-and-unintended upstream code, don't reproduce nondeterministic
// UB" precedent already applied elsewhere in this project when upstream
// code is unambiguously dead rather than a working-but-odd design
// choice.
//
// **The per-row wall-texture-Y division was replaced with the standard
// incremental technique**, not reproduced literally - upstream's own
// `display()` computes `texY` via *two* integer divisions on every
// single row of every wall stripe (`d = y*256 - texH*128 + lineHeight*128;
// texY = ((d*texW)/lineHeight)/256;`), with its own inline comment
// admitting as much ("TODO: avoid the division to speed this up") -
// this is exactly the classic lodev.org "flat" tutorial variant
// upstream's own header credits, and the well-known fix (replacing a
// division-per-row with one division to compute a `step`, then a plain
// addition per row) is the *same* tutorial series' own next, "textured"
// iteration - not a novel guess. Verified equivalent by direct
// derivation: since `texW==texH==64` here, upstream's own two-division
// formula algebraically reduces to `texY = 32*(2y-64+lineHeight)/
// lineHeight`, which is 0 at the unclamped top of a stripe and exactly
// `texH` at its unclamped bottom - the same two boundary conditions the
// incremental `step=texH/lineHeight; texPos=(drawStart-32+lineHeight/2)*
// step` technique produces by construction.
//
// Data tables (both 64x64 textures reused as-is from the already-shipped
// column-atlas-adjacent extraction pipeline; font data reused verbatim
// from Road Rush/DFlight's own already-verified myfont.hpp extraction -
// no cross-game-file sharing mechanism exists in this project, so each
// game keeps its own self-contained copy) extracted via a Python script,
// byte-diff verified against the real counts before use.

