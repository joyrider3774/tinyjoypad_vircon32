void bertTeleportMain()
{
    bertBypassDead = 1;
    bertSprite[ 0 ].gridXpos = 0;
    bertSprite[ 0 ].gridYpos = 0;
}

void bertRefreshJump( int spUse )
{
    int backup = bertSprite[ spUse ].joypadKey;
    if( bertSprite[ spUse ].joypadKey == 2 )
    {
        bertSprite[ spUse ].xPos = bertSprite[ spUse ].xPos + bertJump[ bertSprite[ spUse ].jumpFrame * 2 ];
        bertSprite[ spUse ].yPos = bertSprite[ spUse ].yPos + bertJump[ ( bertSprite[ spUse ].jumpFrame * 2 ) + 1 ];
    }
    if( bertSprite[ spUse ].joypadKey == 3 )
    {
        bertSprite[ spUse ].xPos = bertSprite[ spUse ].xPos + ( -bertJump[ bertSprite[ spUse ].jumpFrame * 2 ] );
        bertSprite[ spUse ].yPos = bertSprite[ spUse ].yPos + bertJump[ ( bertSprite[ spUse ].jumpFrame * 2 ) + 1 ];
    }
    if( bertSprite[ spUse ].joypadKey == 1 )
    {
        bertSprite[ spUse ].xPos = bertSprite[ spUse ].xPos + bertJump[ 32 - ( bertSprite[ spUse ].jumpFrame * 2 ) ];
        bertSprite[ spUse ].yPos = bertSprite[ spUse ].yPos + ( -bertJump[ ( 32 - ( bertSprite[ spUse ].jumpFrame * 2 ) ) + 1 ] );
    }
    if( bertSprite[ spUse ].joypadKey == 4 )
    {
        bertSprite[ spUse ].xPos = bertSprite[ spUse ].xPos + ( -bertJump[ 32 - ( bertSprite[ spUse ].jumpFrame * 2 ) ] );
        bertSprite[ spUse ].yPos = bertSprite[ spUse ].yPos + ( -bertJump[ ( 32 - ( bertSprite[ spUse ].jumpFrame * 2 ) ) + 1 ] );
    }
    bertSprite[ spUse ].jumpFrame = bertSprite[ spUse ].jumpFrame + 1;
    if( bertSprite[ spUse ].jumpFrame > 15 )
    {
        Sound( 160, 10 );
        if( bertDificultPlate == 0 )
        {
            if( bertPlateGrid[ bertSprite[ spUse ].gridYpos ][ bertSprite[ spUse ].gridXpos ] == 0 &&
                spUse == 0 && bertSprite[ spUse ].dead == 0 )
            {
                bertScoreChange();
                bertPlateGrid[ bertSprite[ spUse ].gridYpos ][ bertSprite[ spUse ].gridXpos ] = 1;
                bertPlateDirty = true;
                if( bertLevelCompleted() ) { bertBypassDead = 1; bertChangeLevel = 18; }
            }
        }
        else
        {
            if( spUse == 0 && bertSprite[ spUse ].dead == 0 )
            {
                int cell = bertPlateGrid[ bertSprite[ spUse ].gridYpos ][ bertSprite[ spUse ].gridXpos ];
                if( cell == 1 ) cell = 0; else cell = 1;
                bertPlateGrid[ bertSprite[ spUse ].gridYpos ][ bertSprite[ spUse ].gridXpos ] = cell;
                bertPlateDirty = true;
                if( cell == 1 ) bertScoreChange();
                if( bertLevelCompleted() ) { bertBypassDead = 1; bertChangeLevel = 18; }
            }
        }
        bertSprite[ spUse ].jumpFrame = 0;
        bertSprite[ spUse ].joypadKey = 255;
        if( bertSprite[ spUse ].sw == 2 ) bertSprite[ spUse ].sw = 3;
        if( bertSprite[ spUse ].sw == 0 ) bertSprite[ spUse ].sw = 1;
        if( bertSprite[ spUse ].dead == 1 )
        {
            if( bertSprite[ spUse ].gridXpos == 3 && backup == 1 && bertDestroyLiftR == 0 )
            {
                bertDestroyLiftR = 1; bertTeleportMain(); bertSprite[ spUse ].dead = 3;
            }
            else if( bertSprite[ spUse ].gridYpos == 3 && backup == 4 && bertDestroyLiftL == 0 )
            {
                bertDestroyLiftL = 1; bertTeleportMain(); bertSprite[ spUse ].dead = 3;
            }
            else
            {
                bertSprite[ spUse ].dead = 2;
                if( spUse == 0 ) bertDeadSound();
            }
        }
    }
}

void bertUpdateMainMove( int spUse )
{
    int x = 0;
    if( bertSprite[ spUse ].joypadKey != 0 && bertSprite[ spUse ].joypadKey != 255 && bertSprite[ spUse ].jumpFrame == 0 )
      bertSprite[ spUse ].jumpFrame = 1;
    while( x < 2 )
    {
        if( bertSprite[ spUse ].jumpFrame != 0 ) bertRefreshJump( spUse );
        x++;
    }
}

void bertUpdateMainDead( int spUse )
{
    int x = 0;
    while( x < 2 )
    {
        bertSprite[ spUse ].yPos = bertSprite[ spUse ].yPos + 2;
        x++;
    }
    if( bertSprite[ spUse ].yPos > 120 ) bertSprite[ spUse ].dead = 255;
}

int bertUpdateLiftMain( int spUse )
{
    int x = 0;
    Sound( 100 - bertSprite[ spUse ].yPos, 10 );
    while( x < 2 )
    {
        if( bertSprite[ spUse ].xPos == 58 && bertSprite[ spUse ].yPos == 2 )
        {
            bertSprite[ spUse ].dead = 0;
            bertBypassDead = 0;
        }
        if( spUse != 0 ) return 0;
        if( bertSprite[ spUse ].yPos > 2 ) bertSprite[ spUse ].yPos--;
        else
        {
            if( bertSprite[ spUse ].xPos > 58 ) bertSprite[ spUse ].xPos--;
            if( bertSprite[ spUse ].xPos < 58 ) bertSprite[ spUse ].xPos++;
        }
        x++;
    }
    return 0;
}

void bertBallMoveUpdate( int spUse )
{
    int speed = bertMaxSpeed;
    if( spUse == 0 ) speed = 30;
    if( bertSprite[ spUse ].joypadKey == 255 && bertSprite[ spUse ].dead == 0 )
      bertSprite[ spUse ].joypadKey = 0;
    if( bertSprite[ spUse ].joypadKey == 0 )
    {
        bertSprite[ spUse ].moveTimer1++;
        if( bertSprite[ spUse ].moveTimer1 == speed )
        {
            bertSprite[ spUse ].moveTimer1 = 0;
            int q;
            if( spUse == 1 || bertSprite[ spUse ].gridXpos == 0 || bertSprite[ spUse ].gridYpos == 0 )
              q = bertRandom( 2 );
            else
              q = bertRandom( 4 );

            if( q == 0 ) bertLimitCheck( spUse, 2 );
            else if( q == 1 ) bertLimitCheck( spUse, 3 );
            else if( q == 2 ) bertLimitCheck( spUse, 1 );
            else if( q == 3 ) bertLimitCheck( spUse, 4 );
        }
    }
}

