// =============================================================================
// Tiny Bert - ported from Daniel C's TINY_BERT.ino (tinyjoypad.com, GPLv3).
// Same tinyJoypadShim lineage as Tiny Invaders/Pinball/Pacman/Bomber/Doc
// (FastTinyDriver.h). A Q*bert clone: an isometric 4-row pyramid of plates,
// jump diagonally between them to flip every plate to the target color
// while dodging two enemies (a bouncing ball and a snake/"snack").
//
// Button mapping: same analogRead(A0)/(A3)+digitalRead(1) pattern as every
// other Daniel-C game here - isLeftPressed()/isRightPressed() off A0 map to
// upstream's Joypad_Key 4/2, isDownPressed()/isUpPressed() off A3 map to
// Joypad_Key 3/1 (cross-referenced against the exact analogRead thresholds,
// same as Pinball/Bomber/Pacman's own mapping). isFirePressed() only starts
// a game from the title screen - no in-game action needed.
//
// Structural changes from upstream:
//  - upstream's loop() is NEW_GAME:/NEW_LEVEL:/MENU_LOOP:/START:/FLIP:
//    labels around one big while(1) - rewritten as an explicit frame-
//    stepped state machine, same approach as every other tinyJoypadShim
//    port here.
//  - upstream's main while(1) body actually runs its movement/sprite-update
//    logic block 2-3 times (via a `Time_Management` 0->1->2 counter) for
//    every one `Tiny_Flip()`+`delay_ms(10)` draw - an AVR technique to get
//    smoother movement despite slow i2c-bitbanged drawing, with no real
//    timing model of its own to faithfully match. An earlier revision of
//    this port just ran logic and render once per real 60fps frame (the
//    same simplification used for every dropped real-time frame limiter
//    in this project); a later frame-pacing session (see CLAUDE.md) added
//    a real throttle instead (`BERT_MOVE_DIVISOR`) after the game was
//    reported playing too fast - jump/AI/collision now only advance every
//    other real frame, while `bertTinyFlip()` still renders every real
//    frame for smooth visuals.
//  - `CHANGE_LEVEL`'s 18-step countdown (each step calls `FLIP_PLATE()` to
//    flash the completed pyramid before advancing) was a *blocking* loop
//    upstream (each iteration draws+delays itself); rewritten as its own
//    `BERT_STATE_LEVEL_FLASH` state advancing one step per real engine
//    frame, same "blocking loop -> explicit resumable state" treatment
//    every port here needs.
//  - upstream's `Sprite` struct used C++ in-class default member
//    initializers (`uint8_t sw=1; uint8_t Timer_new_Live=MAX_RENEW;`) that
//    only ever run once (the local `Sprite sprite[3];` in `loop()` is
//    declared exactly once, since `loop()` here never actually returns/
//    re-runs from scratch - it's one big internal goto-loop). Ported as an
//    explicit one-time init in `gameTinyBert_init()` instead.
//  - avoided `switch` and GCC case-ranges entirely (as if/else chains),
//    consistent with every other port in this project - neither construct
//    has been exercised here before, no reason to be the first.
//  - `RANDOM()`'s `rand()`-less lookup-table approach (`RAND2`/`RAND4`,
//    precomputed pseudo-random sequences cycled by a rolling `SEED`) needed
//    no `arand()` fix at all - it never calls the real `rand()`, so the
//    Vircon32-vs-AVR RNG-range mismatch this project fixed elsewhere
//    doesn't apply here.
//  - render loop (`bertTinyFlip`) composites the 3 moving sprites (plus
//    their black cutout masks) once per page row into a shared buffer
//    instead of recomputing all 3 at every pixel, and gates the narrow-
//    range UI layers (lives, score, lifts) by row - both lessons from this
//    session's Tiny Invaders/Bomber/Pacman/Doc CPU-load optimization work,
//    applied from the start instead of needing a later pass. Always
//    redraws the full 128x8 screen (upstream's `Scan` parameter skipped
//    columns 109-127 most frames, relying on real SSD1306 VRAM persistence
//    - the exact bug already found in Doc/Pinball, avoided here from the
//    start).
// =============================================================================

