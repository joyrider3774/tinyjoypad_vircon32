int bertRenewCheckIfPosible( int spr )
{
    if( spr == 2 && bertDificulty <= 5 ) return 0;
    int t;
    for( t = 0; t < 3; t++ )
      if( bertSprite[ t ].dead != 254 )
        if( bertSprite[ t ].yPos < 12 ) return 1;

    if( spr == 0 ) bertRenewSpriteMask = bertRenewSpriteMask & 0xFE;
    else if( spr == 1 ) bertRenewSpriteMask = bertRenewSpriteMask & 0xFD;
    else if( spr == 2 ) bertRenewSpriteMask = bertRenewSpriteMask & 0xFB;

    bertRenewSprite( spr );
    return 0;
}

int bertRenewIfPosible()
{
    if( bertRenewSpriteMask == 0 ) return 0;
    if( ( bertRenewSpriteMask & 0x01 ) != 0 ) return bertRenewCheckIfPosible( 0 );
    if( ( bertRenewSpriteMask & 0x02 ) != 0 ) { bertRenewCheckIfPosible( 1 ); return 0; }
    if( ( bertRenewSpriteMask & 0x04 ) != 0 ) { bertRenewCheckIfPosible( 2 ); return 0; }
    return 0;
}

