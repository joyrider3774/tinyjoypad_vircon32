void bertResetPlateGrid()
{
    int x, y, s;
    for( y = 0; y < 4; y++ )
      for( x = 0; x < 4; x++ )
        bertPlateGrid[ y ][ x ] = 255;
    s = 4;
    for( y = 0; y < 4; y++ )
    {
        for( x = 0; x < s; x++ )
          bertPlateGrid[ y ][ x ] = 0;
        s--;
    }
    bertPlateDirty = true;
}

void bertFlipPlate()
{
    int x, y, s = 4, q;
    if( bertPlateGrid[ 0 ][ 0 ] == 1 ) q = 0; else q = 1;
    for( y = 0; y < 4; y++ )
    {
        for( x = 0; x < s; x++ )
          bertPlateGrid[ y ][ x ] = q;
        s--;
    }
    bertPlateDirty = true;
}

int bertLevelCompleted()
{
    int x, y, s = 4;
    for( y = 0; y < 4; y++ )
    {
        for( x = 0; x < s; x++ )
          if( bertPlateGrid[ y ][ x ] == 0 ) return 0;
        s--;
    }
    return 1;
}

int bertGridLimitTest( int spUse, int x, int y )
{
    if( x == -1 && bertSprite[ spUse ].gridXpos + x >= 0 )
    {
        bertSprite[ spUse ].gridXpos--;
        return 0;
    }
    if( x == 1 && bertSprite[ spUse ].gridXpos + x <= 3 &&
        bertPlateGrid[ bertSprite[ spUse ].gridYpos ][ bertSprite[ spUse ].gridXpos + 1 ] != 255 )
    {
        bertSprite[ spUse ].gridXpos++;
        return 0;
    }
    if( y == -1 && bertSprite[ spUse ].gridYpos + y >= 0 )
    {
        bertSprite[ spUse ].gridYpos--;
        return 0;
    }
    if( y == 1 && bertSprite[ spUse ].gridYpos + y <= 3 &&
        bertPlateGrid[ bertSprite[ spUse ].gridYpos + 1 ][ bertSprite[ spUse ].gridXpos ] != 255 )
    {
        bertSprite[ spUse ].gridYpos++;
        return 0;
    }
    bertSprite[ spUse ].dead = 1;
    return 0;
}

void bertLimitCheck( int spUse, int joyKey )
{
    bertSprite[ spUse ].joypadKey = joyKey;
    if( joyKey == 4 ) { bertSprite[ spUse ].sw = 2; bertGridLimitTest( spUse, -1, 0 ); }
    else if( joyKey == 2 ) { bertSprite[ spUse ].sw = 0; bertGridLimitTest( spUse, 1, 0 ); }
    else if( joyKey == 3 ) { bertSprite[ spUse ].sw = 2; bertGridLimitTest( spUse, 0, 1 ); }
    else if( joyKey == 1 ) { bertSprite[ spUse ].sw = 0; bertGridLimitTest( spUse, 0, -1 ); }
}

