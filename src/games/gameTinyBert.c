int bertCollisionCheck()
{
    int margXMax = 3, margYMax = 3;
    if( bertMainGhost == 1 || bertSprite[ 0 ].dead != 0 ) return 0;
    int x;
    for( x = 1; x < 3; x++ )
    {
        if( ( bertSprite[ 0 ].xPos - margXMax ) > ( bertSprite[ x ].xPos + margXMax ) ||
            ( bertSprite[ 0 ].xPos + margXMax ) < ( bertSprite[ x ].xPos - margXMax ) ||
            ( bertSprite[ 0 ].yPos - margYMax ) > ( bertSprite[ x ].yPos + margYMax ) ||
            ( bertSprite[ 0 ].yPos + margYMax ) < ( bertSprite[ x ].yPos - margYMax ) )
        {
            // no overlap
        }
        else
        {
            bertDeadify( 0 );
            bertRenewSpriteMask = bertRenewSpriteMask | 0x01;
            bertDeadSound();
        }
    }
    return 0;
}

