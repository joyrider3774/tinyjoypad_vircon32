void tmzClearTextBuffer()
{
    for( int i = 0; i < 32; i++ )
      tmzTextBuffer[ i ] = 0;
}

// Writes a 2-digit ASCII decimal representation of value (0-99) starting
// at tmzTextBuffer[offset] - matches upstream's own convertValueToDigits.
void tmzConvertValueToDigits( int value, int offset )
{
    int tens = ( value / 10 ) % 10;
    int ones = value % 10;
    tmzTextBuffer[ offset ] = '0' + tens;
    tmzTextBuffer[ offset + 1 ] = '0' + ones;
}

int tmzDisplayText( int x, int y )
{
    int ch = tmzTextBuffer[ ( x >> 3 ) + y * 4 ];
    if( ch == 0 )
      return 0x00;
    return tmzSegDigits[ ( ch - '0' ) * 8 + ( x & 7 ) ];
}

