// =============================================================================
// Tiny Minez - ported from Sven B's TinyMinez v1.0 (tinyjoypad.com, GPLv3;
// contact Lorandil@gmx.de). Same tinyJoypadShim lineage as Tiny Invaders/
// Pinball/Pacman/Bomber/Doc/Bert/Tris/Arkanoid/Trick (FastTinyDriver.h) -
// button reads/Sound() reuse that shim as-is, plus one new shim primitive
// (isFire2Pressed(), Vircon32's B button) this game is the first to need.
// A Minesweeper clone: a fixed 12x8 grid, place mines by difficulty,
// uncover cells (auto-flood-filling empty ones), flag suspected mines.
//
// Structural changes from upstream, beyond the usual dialect fixes:
//  - upstream's `Game`/`Selection` are real C++ classes (TinyMinezGame.h/
//    TinyMinesGame.cpp, Selection.h/.cpp) - the first port in this project
//    to need the class-to-plain-function conversion that's kept
//    TinyDungeon/Tiny DDug/Tiny SQuest deferred as "too complex" until now.
//    Converted to plain `tmz*` functions operating on flat global state
//    (`tmzLevelData[96]` etc.) instead of a `this`-bound object - the same
//    treatment those three still-deferred games will eventually need.
//  - upstream's `loop()` is a switch-based state machine already (no goto/
//    while(1) spaghetti to untangle) - rewritten as an explicit frame-
//    stepped state machine anyway, since several of its states are
//    themselves *blocking* multi-frame loops:
//    - the difficulty-selection screen was a `do {...} while(!isFirePressed())`
//      loop with its own internal `waitUntilButtonsReleased()` busy-wait -
//      converted to per-frame up/down edge-detection (manual `tmzPrevUp`/
//      `tmzPrevDown` tracking, since tinyJoypadShim has no obonoCoreShim-
//      style `isButtonDown()` edge helper) which naturally debounces the
//      same way the busy-wait did, without blocking.
//    - the main play loop (`while (status != gameWon && status != boom)`)
//      becomes the TMZ_STATE_PLAYING per-frame body directly.
//    - the "hold Fire to flag, tap to uncover" gesture was a blocking
//      `do {...} while(isFirePressed())` loop measuring hold duration via
//      repeated `_delay_ms()` - converted to a per-frame hold-tick counter
//      (`tmzFireHoldTicks`), decided on the release edge, the same
//      press-and-hold pattern NumberPlace's own `NP_SHORT_PRESS`/
//      `NP_LONG_PRESS` already established. Button B (`isFire2Pressed()`)
//      bypasses this entirely for an instant flag-toggle, matching
//      upstream's own "count = isFire2Pressed() ? 255 : 0" trick (which
//      just forced the long-press branch unconditionally) expressed
//      directly instead of replicating the shared-loop mechanism.
//    - the 10-frame "boom" flash (`for(flash=0;flash<10;flash++){...
//      _delay_ms(100);}`, inverted only on the very first iteration) is
//      now `TMZ_STATE_BOOM_FLASH`, one step per real frame.
//    - the post-boom "reveal all mines, wait for Fire" and the win screen
//      were already effectively frame-stepped upstream (their own
//      `while(!isFirePressed())` loops call `RenderImage()` every
//      iteration) - ported directly as `TMZ_STATE_GAME_OVER`/
//      `TMZ_STATE_GAME_WON`.
//  - upstream's 6 full-screen splash bitmaps (title, rules, difficulty-
//    select, boom, game-won, awesome) are RLE-compressed in PROGMEM (a
//    real AVR-flash-size concern - `uCompression.cpp`'s `pgm_RLEdecompress256()`,
//    a control-byte scheme: top 2 bits of each byte select literal-run/
//    generic-repeat/repeat-0x00/repeat-0xFF, bottom 6 bits are the run
//    length). Vircon32 has no such flash-size pressure, so rather than
//    port a whole new runtime decompression codec for this one game, the
//    6 tables were decompressed *once*, offline, into flat 1024-byte
//    arrays (`tools`-style Node script, verified each decompresses to
//    exactly 1024 bytes) - `md_drawColumn()` just indexes them directly,
//    same as every other game's own texture-column data. (There's also a
//    hand-written AVR assembly fast-path, `uDecompression.S` - confirmed
//    by reading it that it's a 1:1 translation of the plain-C branch also
//    present in `uCompression.cpp`, used only on real AVR targets - no
//    assembly semantics needed understanding or porting at all.)
//  - the RNG: upstream's `seed`/`incrementSeed()` fields look like a
//    bespoke PRNG but aren't - they're just an entropy source (the main
//    loop calls `game.incrementSeed()` on every idle frame while polling
//    for input, so `seed` captures "how long the player took to press
//    Fire"), fed once into stdlib `randomSeed()`/`random()` right before
//    mine placement. Vircon32's own RNG needs no such manual seeding
//    ritual (same reasoning as every other port here) - mine placement
//    just calls the shared `arand(n)` helper directly.
//  - the flood-fill `uncoverCells(x,y)` is ported as the exact iterative
//    "repeatedly rescan the whole board until a full pass finds nothing
//    new" algorithm upstream uses (its own comment explains this was
//    chosen *specifically* over the simpler recursive version to save
//    AVR stack space) - Vircon32 has plenty of stack, so the recursive
//    version would have been fine too, but the iterative one is already
//    correct and understood, so there was no reason to rewrite it.
//  - `textUtils.h`'s shared `textBuffer[128]` was dual-purposed upstream
//    (ASCII digit labels *and*, separately, RLE-decompression scratch
//    space, explicitly commented "repurposed to save valuable RAM") -
//    since this port pre-decompresses everything, only the digit-label
//    purpose remains, so `tmzTextBuffer` is sized to what's actually used
//    (32 slots: 4 characters/row x 8 rows) rather than the original 128.
// =============================================================================

