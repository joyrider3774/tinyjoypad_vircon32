// =============================================================================
// Tiny Pacman - ported from Daniel C's tinypacman.ino (tinyjoypad.com,
// GPLv3). Same tinyJoypadShim lineage as Tiny Invaders/Tiny Pinball
// (FastTinyDriver.h) - button reads below reuse that shim as-is.
//
// Button mapping: upstream reads analogRead(A0)/(A3) + digitalRead(1)
// directly rather than isXPressed()-style helpers. Cross-referencing
// against Tiny Invaders' driver (A0=LEFT_RIGHT_BUTTON, A3=UP_DOWN_BUTTON,
// pin 1=FIRE_BUTTON) and what upstream's own DirectionV/DirectionH fields
// actually do to x/y in RefreshCaracter() (DirectionV, despite the name,
// steps x; DirectionH steps y - upstream's own naming, not a porting
// choice) gives a perfectly ordinary mapping, no remap needed:
//   DirectionV=0 (move -x)  <- analogRead(A0) in [750,950) = isLeftPressed()
//   DirectionV=1 (move +x)  <- analogRead(A0) in (500,750) = isRightPressed()
//   DirectionH=0 (move -y)  <- analogRead(A3) in (500,750) = isUpPressed()
//   DirectionH=1 (move +y)  <- analogRead(A3) in [750,950) = isDownPressed()
//   digitalRead(1)==0 (start) = isFirePressed()
// DirectionV/H default to 2 ("no input yet") and upstream never resets them
// to 2 once set - Pacman/ghosts keep moving in the last chosen direction
// until the opposite one is pressed, matching original arcade Pac-Man feel;
// preserved exactly (no "else reset to 2" was added).
//
// Structural changes from upstream, beyond the usual dialect fixes (no
// goto - checkDotPresent/DotsDestroy's bounded division loop became a
// plain `while`; struct-without-typedef; PERSONAGE's per-field
// initializers dropped, set explicitly instead):
//  - upstream's loop() is NEWGAME:/New:/NEWLEVEL:/RESTARTLEVEL: labels
//    around one big while(1) - rewritten as an explicit frame-stepped
//    state machine, the same approach gameTinyInvaders.c's own header
//    comment describes. The label chain has no delay()s between the
//    labels themselves (only inside specific transitions - death, level
//    complete, bonus life), so most of them just become plain function
//    calls chained together; only the delay-bearing transitions became
//    real wait states.
//  - Dropped upstream's own 44ms-per-tick FPS_Control pacing (a real-time
//    frame limiter) and its "only redraw every *other* logic tick" split
//    (`Frame%2==0` gating Tiny_Flip() itself) - both were AVR performance
//    compromises (i2c bit-banging a redraw is slow; capping the overall
//    loop rate kept gameplay speed sane despite that), not needed on
//    Vircon32's own real 60fps redraw. An earlier revision of this port
//    just ran the full tick (movement + redraw) once per real frame as a
//    result, running somewhat faster than upstream's blended ~45fps
//    logic-tick rate - but a later frame-pacing session (see CLAUDE.md)
//    added a real throttle instead (`PAC_FPS`=30, `PAC_TICK_DIVISOR`),
//    after the user reported it played too fast; simpler than reverse-
//    engineering upstream's exact non-uniform "2 ticks bunched together
//    every 44ms" shape, and close enough to it in practice.
//  - `random()%2` (ghost's post-wall-bump new-direction pick) uses
//    Vircon32's raw-32-bit-register rand() the same unsafe way already
//    fixed elsewhere this session - uses the shared `arand(2)` helper
//    instead (see avrCompat.h's own comment on why raw rand()%n is unsafe
//    here).
// =============================================================================

// This port originally ran the whole logic+redraw tick once per real
// 60fps frame (dropping upstream's own 44ms real-time frame limiter as a
// pure AVR-performance compromise not needed here). Ticking at half rate
// instead - PAC_FPS tracks the LOGIC tick rate, not the engine's display
// rate, since every timer derived from it (pacWaitFrames) counts in
// ticks, not real frames.
