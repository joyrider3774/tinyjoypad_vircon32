int checkDotPresent( int dotsNumber )
{
    // O(1) equivalent of the repeated-subtraction loop this was ported
    // from (AVR-GCC avoided real division here) - dotsNumber is always
    // >= 0 (a running count of dots seen so far), so plain / and % match
    // the loop's result exactly.
    int dotBoolPosition = dotsNumber / 8;
    int rest = dotsNumber % 8;
    return pacDotsMem[ dotBoolPosition ] & ( 0x80 >> rest );
}

void pacDotsDestroy( int dotsNumber )
{
    int dotBoolPosition = dotsNumber / 8;
    int rest = dotsNumber % 8;
    int soustraire = 0;
    if( rest == 0 ) soustraire = 0x7F;
    else if( rest == 1 ) soustraire = 0xBF;
    else if( rest == 2 ) soustraire = 0xDF;
    else if( rest == 3 ) soustraire = 0xEF;
    else if( rest == 4 ) soustraire = 0xF7;
    else if( rest == 5 ) soustraire = 0xFB;
    else if( rest == 6 ) soustraire = 0xFD;
    else if( rest == 7 ) soustraire = 0xFE;
    pacDotsMem[ dotBoolPosition ] = pacDotsMem[ dotBoolPosition ] & soustraire;
}

int pacDotsWrite( int x, int y )
{
    int menReturn = 0;
    int mem1 = pacDots[ x + 128 * y ];
    if( mem1 != 0x00 )
    {
        pacDotsCount++;
        if( pacDotsCount == 0 || pacDotsCount == 1 || pacDotsCount == 12 || pacDotsCount == 13 ||
            pacDotsCount == 50 || pacDotsCount == 51 || pacDotsCount == 62 || pacDotsCount == 63 )
          menReturn = 1;
        else
          menReturn = 0;

        if( checkDotPresent( pacDotsCount ) == 0x00 )
          mem1 = 0x00;
        else
        {
            if( pacSprite[ 0 ].type == PAC_PACMAN &&
                pacSprite[ 0 ].x < x && pacSprite[ 0 ].x > x - 6 &&
                ( ( pacSprite[ 0 ].y == y && pacSprite[ 0 ].Decalagey < 6 ) ||
                  ( pacSprite[ 0 ].y == y - 1 && pacSprite[ 0 ].Decalagey > 5 ) ) )
            {
                pacDotsDestroy( pacDotsCount );
                if( menReturn == 1 ) { pacTimerGobeActive = pacLevelSpeed; pacGobeActive = 1; }
                // Upstream: Sound(10,10);Sound(50,10); - real freq/dur,
                // same reasoning as the ghost-eaten cue above.
                else pacStartSfx2( 2040.8, 0.005, 2439.0, 0.004 );
            }
        }
    }
    if( menReturn == 1 )
    {
        if( ( pacFrame >= 6 && pacFrame <= 12 ) || ( pacFrame >= 18 && pacFrame <= 24 ) )
          return 0x00;
        return mem1;
    }
    return mem1;
}

