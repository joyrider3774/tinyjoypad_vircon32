// Upstream never had a real timing model (no millis()/_delay_ms() pacing
// anywhere in its gameplay loop - see CLAUDE.md's frame-pacing survey), so
// unlike NumberPlace/HollowSeeker/t2048/Doc there's no genuine original
// FPS to reproduce; this port itself invented every existing wait/blink/
// animation timer here assuming a tick happens every real 60fps frame
// (e.g. trkWaitFrames's own "~600ms at 60fps" comment). Throttling the
// *whole* update() the way the 4 genuine-rate games are throttled would
// silently double every one of those already-tuned real-time durations as
// a side effect. Instead, only the movement/physics/AI/collision step is
// gated to run every TRK_MOVE_DIVISOR real frames (the same decouple-
// logic-from-redraw approach already used for Tiny Arkanoid's paddle/ball
// updates) - trkTinyFlip() keeps rendering every real frame for smooth
// visuals, and every existing wait-timer keeps its original real-time
// pacing untouched.
