// =============================================================================
// Tiny Trick - ported from Daniel C's Tiny-trick.ino (tinyjoypad.com, GPLv3).
// Same tinyJoypadShim lineage as Pinball/Pacman/Bomber/Doc/Bert/Tris/Arkanoid
// (FastTinyDriver.h) - button reads/Sound() reuse that shim as-is. An air-
// hockey game: player (white) and computer (black) paddles knock a puck
// around a rink, scoring by getting it past the opponent's goalie into the
// left/right goal - first to 10 points wins.
//
// Button mapping: isUpPressed()/isDownPressed()/isLeftPressed()/
// isRightPressed() off A3/A0 (free 2D paddle movement, same axis/thresholds
// as every other Daniel-C game here), isFirePressed() off digitalRead(1)
// (hits the puck while it's being "dragged" by the paddle).
//
// Structural changes from upstream, applying every lesson from this
// session's earlier ports from the start:
//  - upstream's loop() is an INTRO:/Start_Game:/RESTART: goto-chain around
//    two while(1)s (the title-screen blink loop, and the main play loop) -
//    rewritten as an explicit frame-stepped state machine, same approach as
//    every other tinyJoypadShim port here. The goal-scored sequence
//    (`SCREEN_GOAL()`, a blocking slide-in/hold/slide-out animation built
//    from 13 chained intro() calls plus two _delay_ms() pauses) becomes its
//    own run of sub-states (GOAL_SLIDE_IN/HOLD/SLIDE_OUT/HOLD2), each
//    advancing one step per real engine frame instead of looping to
//    completion inside a single frame - the same "blocking loop -> explicit
//    resumable state" treatment every port here has needed.
//  - `Recupe()`'s composite is a *subtractive* mask (`background &
//    ~sprite1 & ~sprite2 & ... & ~sprite5`, forcing every sprite's own
//    silhouette to solid black regardless of the busy rink texture
//    underneath) rather than the OR-based "solid white sprite" composite
//    every other game here uses. By De Morgan's law
//    `~s1 & ~s2 & ... = ~(s1|s2|...)`, so this port ORs all 5 sprites'
//    contributions into one shared per-page buffer exactly like every
//    other game's own compositing (`trkCompositeSpritesIntoBuffer()`),
//    then inverts and ANDs the *combined* mask against the background just
//    once at the end - same simpler shared-buffer shape, applied to a
//    subtractive composite instead of an additive one.
//  - built the 5-sprite composite (player, computer, puck, 2 goalies) with
//    per-object-per-page footprint gating *from the start* (row + x-range,
//    using each sprite's own known width/height) rather than calling
//    `blitzSprite` unconditionally for all 1024 pixels/frame and relying on
//    its own internal bounds check alone - the exact lesson Tiny Arkanoid's
//    CPU-load report taught this session (a correctly self-gated function
//    still costs a real per-call overhead multiplied by how often it's
//    called, not just by its own body cost).
//  - the title screen only redraws on two exact `TIMER` values (a blink,
//    matching upstream's own `switch(TIMER){case 0:...;case 128:...}` with
//    no `default` redraw) - same "skip the whole draw call most frames"
//    shape as Tiny Tris's attract screen and the obono games' idle
//    screens, so this port also exposes an `onResume` hook
//    (`gameTinyTrick_forceRedraw()`) forcing one extra redraw when resuming
//    from the quit-confirmation dialog, for the same reason those needed
//    it - otherwise the dialog's own pixels could linger indefinitely on
//    whichever half of the blink cycle isn't due to redraw again soon.
//  - `SND()`'s cases 0, 1, and 5 are 20-30-iteration `for` loops of chained
//    blocking `Sound()` calls upstream (a buzzy alarm-style effect) -
//    simplified to a handful of representative `Sound()` calls each,
//    matching the simplification already applied to other games' longer
//    tone sequences (Tris's SND_TTRIS, Arkanoid's SND) rather than
//    reproducing dozens of calls that would all fire in the same instant
//    on a non-blocking engine anyway.
// =============================================================================

