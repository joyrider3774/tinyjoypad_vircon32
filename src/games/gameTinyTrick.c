int trkRecupeLineY( int valeur )
{
    return valeur >> 3;
}

int trkRecupeDecalageY( int valeur )
{
    return valeur - ( ( valeur >> 3 ) * 8 );
}

int trkSplitSpriteDecalageY( int decalage, int input, int upOrDown )
{
    if( upOrDown )
      return input << decalage;
    return input >> ( 8 - decalage );
}

int trkBlitzSprite( int xPos, int yPos, int xPass, int yPass, int frame, int* sprites )
{
    int wSprite = sprites[ 0 ];
    int hSprite = sprites[ 1 ];
    int wMax = ( hSprite * wSprite ) + 1;
    int picByte = frame * ( wMax - 1 );
    int recupeLineY = trkRecupeLineY( yPos );

    if( xPass > ( xPos + ( wSprite - 1 ) ) || xPass < xPos ||
        recupeLineY > yPass || ( recupeLineY + hSprite ) < yPass )
      return 0;

    int spriteYLine = yPass - recupeLineY;
    int spriteYDecalage = trkRecupeDecalageY( yPos );
    int scanA = ( ( xPass - xPos ) + ( spriteYLine * wSprite ) ) + 2;
    int scanB = ( ( xPass - xPos ) + ( ( spriteYLine - 1 ) * wSprite ) ) + 2;

    int outByte;
    if( scanA > wMax )
      outByte = 0;
    else
      outByte = trkSplitSpriteDecalageY( spriteYDecalage, sprites[ scanA + picByte ], 1 );

    if( spriteYLine > 0 )
    {
        int outByte2 = trkSplitSpriteDecalageY( spriteYDecalage, sprites[ scanB + picByte ], 0 );
        if( scanB > wMax ) return outByte;
        return outByte | outByte2;
    }
    return outByte;
}

int trkPatinoire1_2( int xPass, int yPass )
{
    if( xPass > 63 )
      return trkPatinoire[ ( 127 - xPass ) + ( yPass * 64 ) ];
    return trkPatinoire[ xPass + ( yPass * 64 ) ];
}

