int bomScanHRecupe( int upOrDown, int decalage )
{
    if( upOrDown == 0 )
      return ( 0x7F << decalage ) & 0xFF;
    return 0x7F >> ( 8 - decalage );
}

int bomTrim( int y1OrY2, int trimValue, int decalage )
{
    int comp;
    if( y1OrY2 == 0 )
      comp = ( 0x7F << decalage ) & 0xFF;
    else
      comp = 0x7F >> ( 8 - decalage );
    return trimValue & comp;
}

int bomRecupeBackToCompVIdx( int idx )
{
    if( idx > 1023 || idx < 0 ) return 0x00;
    return bomBack[ idx ];
}

int bomRecupeBackToCompV( int spriteCheck )
{
    int y1 = 0, y2 = 0;
    int maxV = bomSprite[ spriteCheck ].x + 6;
    int minV = bomSprite[ spriteCheck ].x;
    if( bomSprite[ spriteCheck ].DirectionV == 1 )
    {
        y1 = bomRecupeBackToCompVIdx( bomSprite[ spriteCheck ].y * 128 + maxV );
        y2 = bomRecupeBackToCompVIdx( ( bomSprite[ spriteCheck ].y + 1 ) * 128 + maxV );
    }
    else if( bomSprite[ spriteCheck ].DirectionV == 0 )
    {
        y1 = bomRecupeBackToCompVIdx( bomSprite[ spriteCheck ].y * 128 + minV );
        y2 = bomRecupeBackToCompVIdx( ( bomSprite[ spriteCheck ].y + 1 ) * 128 + minV );
    }
    y1 = bomTrim( 0, y1, bomSprite[ spriteCheck ].Decalagey );
    y2 = bomTrim( 1, y2, bomSprite[ spriteCheck ].Decalagey );
    if( y1 != 0 || y2 != 0 ) return 1;
    return 0;
}

int bomRecupeBackToCompH( int spriteCheck )
{
    int tempByte;
    int t;
    if( bomSprite[ spriteCheck ].DirectionH == 0 )
    {
        int recupe = bomScanHRecupe( 0, bomSprite[ spriteCheck ].Decalagey );
        for( t = 0; t <= 6; t++ )
        {
            int idx = bomSprite[ spriteCheck ].y * 128 + ( bomSprite[ spriteCheck ].x + t );
            if( idx > 1023 || idx < 0 ) tempByte = 0x00;
            else tempByte = bomBack[ idx ];
            if( ( recupe & tempByte ) != 0 ) return 1;
        }
    }
    else if( bomSprite[ spriteCheck ].DirectionH == 1 )
    {
        int tadd = 0;
        if( bomSprite[ spriteCheck ].Decalagey > 2 ) tadd = 1;
        int recupe = bomScanHRecupe( tadd, bomSprite[ spriteCheck ].Decalagey );
        for( t = 0; t <= 6; t++ )
        {
            int idx = ( bomSprite[ spriteCheck ].y + tadd ) * 128 + ( bomSprite[ spriteCheck ].x + t );
            if( idx > 1023 || idx < 0 ) tempByte = 0x00;
            else tempByte = bomBack[ idx ];
            if( ( recupe & tempByte ) != 0 ) return 1;
        }
    }
    return 0;
}

int bomCheckCollisionWithBomb( int spriteCheck )
{
    if( spriteCheck == 0 ) return 0;
    int x1 = bomSprite[ spriteCheck ].x, y1 = bomSprite[ spriteCheck ].y * 8 + bomSprite[ spriteCheck ].Decalagey;
    int x2 = bomBombXY[ 0 ], y2 = bomBombXY[ 1 ] * 8;
    if( x1 + 7 < x2 || y1 + 7 < y2 || x1 > x2 + 7 || y1 > y2 + 7 ) return 0;
    return 1;
}

int bomCheckCollisionWithBlock( int spriteCheck )
{
    int a = bomSprite[ spriteCheck ].x;
    int aa = a + 7;
    int b = ( ( bomSprite[ spriteCheck ].y - 1 ) * 8 + bomSprite[ spriteCheck ].Decalagey ) / 8;
    int bb = ( ( bomSprite[ spriteCheck ].y - 1 ) * 8 + bomSprite[ spriteCheck ].Decalagey + 7 ) / 8;
    int rest = 0;
    int readBloc = bomBlocDetect[ a ];
    if( readBloc != 0xFF && readBloc != 0xFE )
    {
        rest = rest + bomBoolRead( readBloc + b * 15 );
        rest = rest + bomBoolRead( readBloc + bb * 15 );
    }
    readBloc = bomBlocDetect[ aa ];
    if( readBloc != 0xFF && readBloc != 0xFE )
    {
        rest = rest + bomBoolRead( readBloc + b * 15 );
        rest = rest + bomBoolRead( readBloc + bb * 15 );
    }
    return rest;
}

int bomCheckCollisionWithBack( int spriteCheck, int horVCheck )
{
    int backToComp;
    if( horVCheck == 1 )
      backToComp = bomRecupeBackToCompV( spriteCheck );
    else
      backToComp = bomRecupeBackToCompH( spriteCheck );
    backToComp = backToComp + bomCheckCollisionWithBlock( spriteCheck );
    backToComp = backToComp + bomCheckCollisionWithBomb( spriteCheck );
    if( backToComp != 0 ) return 1;
    return 0;
}

