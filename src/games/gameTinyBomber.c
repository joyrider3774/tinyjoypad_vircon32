// =============================================================================
// Tiny Bomber - ported from Daniel C's tiny-bomber.ino (tinyjoypad.com,
// GPLv3). Same tinyJoypadShim lineage as Tiny Invaders/Pinball/Pacman
// (FastTinyDriver.h) - button reads below reuse that shim as-is.
//
// Button mapping: same analysis as gameTinyPacman.c (same author, same
// analogRead(A0)/(A3)+digitalRead(1) pattern, same DirectionV/H naming
// swap) - DirectionV (steps x) <- isLeftPressed()/isRightPressed() off A0,
// DirectionH (steps y) <- isUpPressed()/isDownPressed() off A3,
// digitalRead(1) <- isFirePressed() (doubles as "confirm start" and "place
// bomb", same button, gated by state exactly like upstream). Unlike
// Pacman, this game's direction fields *do* reset to their "stopped"
// sentinel (2) - but only once the character reaches the next grid cell
// (`x%8==0` / `Decalagey==0`), not immediately on button release - a grid-
// snapping behavior preserved exactly.
//
// Structural changes from upstream, beyond the usual dialect fixes
// (BOOLWRITE0's bounded division loop's `goto DECREASE` became a plain
// `while`; struct-without-typedef; no goto elsewhere - see below):
//  - upstream's loop() is NEWGAME:/NEWLEVEL:/RESTARTLEVEL: labels around
//    one big while(1) - rewritten as an explicit frame-stepped state
//    machine, same approach as the other tinyJoypadShim ports.
//  - `StartGame()`'s upstream busy-wait for the button to be *released*
//    (`while(1){if(digitalRead(1)==1){break;}}`, preventing the same press
//    that confirms "start" from also instantly placing a bomb) is exactly
//    what `md_armInputFireGate()` already does for this project (see
//    gameTinyInvaders.c) - used instead of a real blocking wait.
//  - Dropped the 44ms `FPS_Control` real-time frame limiter and the
//    "only redraw every *other* logic tick" split, same reasoning as
//    gameTinyPacman.c's header comment (AVR performance compromises this
//    project's fast redraw-every-frame model doesn't need).
//  - `random()%2` (ghost direction pick after a wall bump) uses the shared
//    `arand(2)` helper instead, same fix as Pacman/HollowSeeker.
//  - DeadSong()'s and the level-clear fanfare's real-time ~254/~510-step
//    tone sweeps are approximated with a handful of representative tones
//    plus a fixed wait, same simplification already used throughout this
//    project's other ports for AVR busy-wait sound effects.
// =============================================================================

