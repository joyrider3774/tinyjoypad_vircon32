void bomRefreshCaracter()
{
    int t;
    for( t = 0; t <= 4; t++ )
    {
        if( ( t != 0 && bomSpeedBomber == 1 ) || bomFrame % 2 == 0 )
        {
            int memx = bomSprite[ t ].x;
            int memy = bomSprite[ t ].y;
            int memDecalagey = bomSprite[ t ].Decalagey;

            if( bomSprite[ t ].DirectionV == 1 ) bomSprite[ t ].x++;
            if( bomSprite[ t ].DirectionV == 0 ) bomSprite[ t ].x--;
            if( bomCheckCollisionWithBack( t, 1 ) )
            {
                if( t != 0 ) bomSprite[ t ].DirectionV = arand( 2 );
                else bomSprite[ t ].DirectionV = 2;
                bomSprite[ t ].x = memx;
            }

            if( bomSprite[ t ].DirectionH == 1 )
            {
                if( bomSprite[ t ].Decalagey < 7 ) bomSprite[ t ].Decalagey++;
                else { bomSprite[ t ].Decalagey = 0; bomSprite[ t ].y++; }
            }
            if( bomSprite[ t ].DirectionH == 0 )
            {
                if( bomSprite[ t ].Decalagey > 0 ) bomSprite[ t ].Decalagey--;
                else { bomSprite[ t ].Decalagey = 7; bomSprite[ t ].y--; }
            }
            if( bomCheckCollisionWithBack( t, 0 ) )
            {
                if( t != 0 ) bomSprite[ t ].DirectionH = arand( 2 );
                else bomSprite[ t ].DirectionH = 2;
                bomSprite[ t ].y = memy;
                bomSprite[ t ].Decalagey = memDecalagey;
            }

            if( t == 0 )
            {
                if( bomFrame % 2 == 0 )
                {
                    if( bomSprite[ t ].DirectionH == 1 ) bomSprite[ t ].DirectionAnim = 0;
                    if( bomSprite[ t ].DirectionH == 0 ) bomSprite[ t ].DirectionAnim = 2 * 3;
                    if( bomSprite[ t ].DirectionV == 1 ) bomSprite[ t ].DirectionAnim = 3 * 3;
                    if( bomSprite[ t ].DirectionV == 0 ) bomSprite[ t ].DirectionAnim = 1 * 3;
                }
            }
            else
            {
                if( bomFrame == 0 || bomFrame == 12 )
                {
                    bomSprite[ t ].DirectionAnim = 0;
                }
            }

            if( t == 0 )
            {
                if( bomFrame % 2 == 0 )
                {
                    if( bomSprite[ 0 ].switchanim == 0 )
                    {
                        if( bomSprite[ 0 ].anim < 2 && ( bomSprite[ t ].DirectionH != 2 || bomSprite[ t ].DirectionV != 2 ) )
                          bomSprite[ 0 ].anim++;
                        else
                          bomSprite[ 0 ].switchanim = 1;
                    }
                    else
                    {
                        if( bomSprite[ 0 ].anim > 0 ) bomSprite[ 0 ].anim--;
                        else bomSprite[ 0 ].switchanim = 0;
                    }
                }
            }
            else
            {
                if( bomFrame % 6 == 0 )
                {
                    if( bomSprite[ t ].anim < 2 ) bomSprite[ t ].anim++;
                    else bomSprite[ t ].anim = 0;
                }
            }
        }
    }
}

