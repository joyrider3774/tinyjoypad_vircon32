void bomLoadLevel( int level )
{
    int t;
    for( t = 0; t < 14; t++ )
      bomBlocBombMem[ t ] = bomLevelData[ t + level * 14 ];
}

void bomBoolWrite0( int boolNumber )
{
    if( boolNumber < 0 || boolNumber > 105 ) return;
    // Equivalent to the repeated-subtraction loop this was ported from
    // (AVR-GCC avoided real division here), but O(1) instead of O(n) -
    // safe since boolNumber is already guarded to 0..105 above, so the
    // division can't produce an out-of-range dotBoolPosition.
    int dotBoolPosition = boolNumber / 8;
    int rest = boolNumber % 8;
    int soustraire = 0;
    if( rest == 0 ) soustraire = 0x7F;
    else if( rest == 1 ) soustraire = 0xBF;
    else if( rest == 2 ) soustraire = 0xDF;
    else if( rest == 3 ) soustraire = 0xEF;
    else if( rest == 4 ) soustraire = 0xF7;
    else if( rest == 5 ) soustraire = 0xFB;
    else if( rest == 6 ) soustraire = 0xFD;
    else if( rest == 7 ) soustraire = 0xFE;
    bomBlocBombMem[ dotBoolPosition ] = bomBlocBombMem[ dotBoolPosition ] & soustraire;
}

int bomBoolRead( int numero )
{
    if( numero < 0 || numero > 105 ) return 0;
    // Same O(1) division rewrite as bomBoolWrite0() above.
    int int8Chose = numero / 8;
    int byteCheck = numero % 8;
    int var0 = 0;
    if( byteCheck == 0 ) var0 = 0x80;
    else if( byteCheck == 1 ) var0 = 0x40;
    else if( byteCheck == 2 ) var0 = 0x20;
    else if( byteCheck == 3 ) var0 = 0x10;
    else if( byteCheck == 4 ) var0 = 0x08;
    else if( byteCheck == 5 ) var0 = 0x04;
    else if( byteCheck == 6 ) var0 = 0x02;
    else if( byteCheck == 7 ) var0 = 0x01;
    if( ( bomBlocBombMem[ int8Chose ] & var0 ) != 0 ) return 1;
    return 0;
}

