// =============================================================================
// Tiny Arkanoid - ported from Daniel C's tiny-arkanoid.ino (tinyjoypad.com,
// GPLv3). Same tinyJoypadShim lineage as Pinball/Pacman/Bomber/Doc/Bert/Tris
// (FastTinyDriver.h) - button reads/Sound() reuse that shim as-is. A Breakout/
// Arkanoid clone: a paddle moves along the left edge (up/down), launching a
// ball that bounces around a 6-row x 5-column block grid on the right side.
//
// Button mapping: isUpPressed()/isDownPressed() off A3 (paddle up/down, same
// axis/thresholds as every other Daniel-C game here), isFirePressed() off
// digitalRead(1) (launches the ball). LEFT/RIGHT are also accepted as
// aliases for UP/DOWN (not present upstream, added since this game's own
// art is drawn sideways as if meant to be played with the display
// rotated - Vircon32's screen can't rotate, so both d-pad axes move the
// paddle the same way to make either physical orientation feel natural.
//
// Structural changes from upstream, applying every lesson from this
// session's earlier ports from the start:
//  - upstream's loop() is a NEWGAME:/ONE:/NEXTLEVEL:/RESTARTLEVEL:
//    goto-chain around a while(1) - rewritten as an explicit frame-stepped
//    state machine, same approach as every other tinyJoypadShim port here.
//  - `Tiny_Flip()` here already redraws the full 128x8 screen unconditionally
//    (no partial-width trick like Pinball/Doc/Tris had to unlearn) - nothing
//    to fix there. Upstream DID gate its own call to Tiny_Flip(0) behind
//    `Frame%32==0` (an AVR perf compromise, redrawing only once every 32
//    loop iterations) - dropped like every other port's frame-skip-redraw
//    optimization; this port redraws every real engine frame instead.
//  - `PLAYMUSIC()` (a 46-note intro jingle) and the 4/5-note "life lost"/
//    "level cleared" cues are genuinely blocking, sequential Sound() calls
//    upstream (each Sound() call itself blocks for its own duration) -
//    rewritten as a small shared frame-stepped note sequencer
//    (`arkStartNoteSeq`/`arkAdvanceNoteSeq`) that fires one note at a time,
//    waiting the note's own real-time duration (converted to frames using
//    the exact same freq/dur formula `Sound()` itself already uses) before
//    advancing - same "blocking loop -> explicit resumable state" treatment
//    every port here has needed, just applied to actual sequenced music for
//    the first time rather than a handful of simultaneous representative
//    tones.
//  - `background()`'s upstream implementation used a stateful `SWIFT_TEXTURE`
//    counter (reset at x==0, incremented per column) purely to cycle through
//    the 15-entry `texture[]` table - traced the exact reset/increment
//    order and confirmed the resulting index is always exactly
//    `(x+1) % 15` regardless of row, so this port computes that directly
//    instead of carrying the stateful counter across calls (simpler, no
//    call-order dependency risk from this port's own compositing).
//  - `RecupeDecalageY()`'s `while(Valeur>7){Valeur-=8;}` (an AVR-cheap-
//    division-avoidance loop) replaced with a plain `% 8` - Vircon32 has
//    real division, same simplification already applied to other games'
//    equivalent helpers (Tris, Pacman/Bomber's dot/block bitmap lookups).
//  - `ResetVar()`'s equivalent wraparound loop (`while(f>4){f-=5;}`,
//    wrapping the level index into the 5 available level layouts)
//    similarly replaced with `% 5`.
//  - dropped a couple of upstream's own dead/no-op AVR artifacts rather
//    than porting them literally: `Ball()`'s first bounds check
//    (`(X-uint8_t(BALLXPOS))<0`) is always false in unsigned arithmetic
//    (a redundant leftover, the very next line's signed comparison is the
//    real bounds check); `Ballxposflip`/`Ballyposflip` struct fields are
//    declared upstream but never referenced anywhere in the file, so they
//    were not ported at all.
// =============================================================================

