void arkLoadLevel( int level )
{
    int a, b;
    for( b = 0; b < 5; b++ )
      for( a = 0; a < 6; a++ )
        arkBlocsGrid[ a ][ b ] = arkLevelData[ ( level * 30 ) + b + ( a * 5 ) ];
}

void arkRsVarNewGame()
{
    arkLevelSpeed = 16;
    arkLevel = 1;
    arkLive = 3;
    arkAnimReflect = 0;
    arkLoadLevel( 0 );
}

void arkResetVar()
{
    int f = arkLevel % 5;
    arkLoadLevel( f );
    arkLaunch = 0;
}

void arkResetBall()
{
    arkAnimReflect = 0;
    arkTrackBary = 2;
    arkTrackBaryDecal = 4;
    arkBallxpos = 8;
    arkSimBallxpos = 8;
    arkBallypos = 32;
    arkSimBallypos = 32;
    arkBallSpeedx = 1;
    arkSimBallSpeedx = 1;
    if( arkFrame > 32 )
    {
        arkBallSpeedy = 0.41;
        arkSimBallSpeedy = 0.41;
    }
    else
    {
        arkBallSpeedy = 0.47;
        arkSimBallSpeedy = 0.47;
    }
    arkLaunch = 0;
}

bool arkBallMissing()
{
    if( arkBallxpos < 0 )
      return true;
    return false;
}

bool arkCheckLevelEnded()
{
    int h, v;
    bool res = true;
    for( v = 0; v < 5; v++ )
      for( h = 0; h < 6; h++ )
        if( arkBlocsGrid[ h ][ v ] != 255 && arkBlocsGrid[ h ][ v ] != 5 )
          res = false;
    return res;
}

// -----------------------------------------------------------------------------
//   Ball physics
