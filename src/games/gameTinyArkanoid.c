void arkRecupeBallPosForSim()
{
    arkSimBallxpos = arkBallxpos;
    arkSimBallypos = arkBallypos;
    arkSimBallSpeedx = arkBallSpeedx;
    arkSimBallSpeedy = arkBallSpeedy;
}

void arkTestMoveBall()
{
    arkSimBallxpos = arkSimBallxpos + arkSimBallSpeedx;
    arkSimBallypos = arkSimBallypos + arkSimBallSpeedy;
}

void arkSimulMove( int sim )
{
    if( sim == 0 ) { arkSimBallSpeedx = arkBallSpeedx; arkSimBallSpeedy = arkBallSpeedy; }
    else if( sim == 1 ) { arkSimBallSpeedx = -arkBallSpeedx; arkSimBallSpeedy = arkBallSpeedy; }
    else if( sim == 2 ) { arkSimBallSpeedx = arkBallSpeedx; arkSimBallSpeedy = -arkBallSpeedy; }
    else if( sim == 3 ) { arkSimBallSpeedx = -arkBallSpeedx; arkSimBallSpeedy = -arkBallSpeedy; }
    else if( sim == 4 ) { arkSimBallSpeedx = -arkBallSpeedy; arkSimBallSpeedy = -arkBallSpeedx; }
    else if( sim == 5 ) { arkSimBallxpos = arkBallxpos + 1; arkSimBallypos = arkBallypos; arkSimBallSpeedx = -1; arkSimBallSpeedy = 1; }
    else if( sim == 6 ) { arkSimBallxpos = arkBallxpos + 1; arkSimBallypos = arkBallypos; arkSimBallSpeedx = -1; arkSimBallSpeedy = -1; }
}

int arkRecupeXPositionOnGrid()
{
    if( arkSimBallxpos >= 66 && arkSimBallxpos < 72 ) return 0;
    else if( arkSimBallxpos >= 72 && arkSimBallxpos < 78 ) return 1;
    else if( arkSimBallxpos >= 78 && arkSimBallxpos < 84 ) return 2;
    else if( arkSimBallxpos >= 84 && arkSimBallxpos < 90 ) return 3;
    else if( arkSimBallxpos >= 90 && arkSimBallxpos < 96 ) return 4;
    return 255;
}

int arkRecupeYPositionOnGrid()
{
    if( arkSimBallypos >= 8 && arkSimBallypos < 16 ) return 0;
    else if( arkSimBallypos >= 16 && arkSimBallypos < 23 ) return 1;
    else if( arkSimBallypos >= 23 && arkSimBallypos < 31 ) return 2;
    else if( arkSimBallypos >= 31 && arkSimBallypos < 40 ) return 3;
    else if( arkSimBallypos >= 40 && arkSimBallypos < 48 ) return 4;
    else if( arkSimBallypos >= 48 && arkSimBallypos < 55 ) return 5;
    return 255;
}

void arkRecupePositionOnGrid()
{
    arkPx = arkRecupeXPositionOnGrid();
    arkPy = arkRecupeYPositionOnGrid();
}

bool arkCheckCollisionWithTrackbar()
{
    int track = ( arkTrackBary * 8 ) + arkTrackBaryDecal;
    if( arkSimBallxpos > 6 || arkSimBallxpos < 5 ) return false;
    if( track > arkSimBallypos ) return false;
    if( ( track + 16 ) < arkSimBallypos ) return false;
    arkTrackAngleOut = (int)( ( ( arkSimBallypos - track ) * 200.0 ) / 16.0 ) - 100;
    return true;
}

bool arkCheckCollisionWithBlock()
{
    arkRecupePositionOnGrid();
    if( arkPx == 255 || arkPy == 255 ) return false;
    if( arkBlocsGrid[ arkPy ][ arkPx ] == 5 )
    {
        Sound( 210, 50 );
        arkAnimReflect = 0;
        return true;
    }
    if( arkBlocsGrid[ arkPy ][ arkPx ] == 255 ) return false;
    Sound( 150, 10 );
    arkBlocsGrid[ arkPy ][ arkPx ] = 255;
    return true;
}

bool arkCheckCollisionBall()
{
    if( arkSimBallxpos > 106 ) return true;
    if( arkSimBallypos > 59 ) return true;
    if( arkSimBallypos < 4 ) return true;
    if( arkCheckCollisionWithTrackbar() )
    {
        Sound( 60, 10 );
        return true;
    }
    if( arkCheckCollisionWithBlock() ) return true;
    return false;
}

void arkWriteBallMove()
{
    float correctionY = arkSimBallSpeedy + ( arkTrackAngleOut / 100.0 );
    if( correctionY < -1 ) correctionY = -1;
    if( correctionY > 1 ) correctionY = 1;
    arkBallxpos = arkSimBallxpos;
    arkBallypos = arkSimBallypos;
    arkBallSpeedx = arkSimBallSpeedx;
    arkBallSpeedy = correctionY;
    arkBallyDecal = arkRecupeDecalageY( (int)( arkBallypos - 1 ) );
    arkYpos = (int)( ( arkBallypos - 1 ) / 8 );
}

void arkUpdateBall()
{
    arkTrackAngleOut = 0;
    int t1;
    for( t1 = 0; t1 <= 6; t1++ )
    {
        arkRecupeBallPosForSim();
        if( arkLaunch == 0 ) break;
        arkSimulMove( t1 );
        arkTestMoveBall();
        if( arkCheckCollisionBall() == false ) break;
    }
    arkWriteBallMove();
}

