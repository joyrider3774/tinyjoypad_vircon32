int arkPannelLevel( int x, int y )
{
    if( y < 5 || y > 6 || x < 117 || x > 123 ) return 0;
    int val10 = arkLevel / 10;
    int val01 = arkLevel - ( val10 * 10 );
    if( y == 5 ) return arkDigital[ ( x - 117 ) + ( val10 * 7 ) ];
    if( y == 6 ) return arkDigital[ ( x - 117 ) + ( val01 * 7 ) ];
    return 0;
}

int arkDrawBlock( int x, int y )
{
    if( x < 67 || x >= 97 || y < 1 || y > 6 ) return 0;
    int xValue = 255;
    if( x < 73 ) xValue = 0;
    else if( x < 79 ) xValue = 1;
    else if( x < 85 ) xValue = 2;
    else if( x < 91 ) xValue = 3;
    else if( x < 97 ) xValue = 4;
    if( xValue == 255 ) return 0;
    int blockType = arkBlocsGrid[ y - 1 ][ xValue ];
    if( blockType == 255 ) return 0;
    int col = ( x - 67 ) - ( xValue * 6 );
    if( blockType == 5 )
      return arkBlockReflect[ col + ( arkAnimReflect * 6 ) ] | arkBlock[ col + ( blockType * 6 ) ];
    return arkBlock[ col + ( blockType * 6 ) ];
}

int arkDrawBall( int x, int y )
{
    int ballX = (int)( arkBallxpos - 1 );
    if( y < arkYpos || y > arkYpos + 1 ) return 0;
    if( x < ballX || x > ballX + 2 ) return 0;
    if( arkBallyDecal == 0 )
    {
        if( y == arkYpos ) return arkBallSprite[ x - ballX ];
        return 0;
    }
    int decal = arkRecupeDecalageY( (int)( arkBallypos - 1 ) );
    if( y == arkYpos ) return arkSplitSpriteDecalageY( decal, arkBallSprite[ x - ballX ], 1 );
    if( y == arkYpos + 1 ) return arkSplitSpriteDecalageY( decal, arkBallSprite[ x - ballX ], 0 );
    return 0;
}

int arkDrawTrackBar( int x, int y )
{
    if( x > 6 ) return 0;
    if( x < 3 ) return 0;
    if( y >= 3 + arkTrackBary ) return 0;
    if( y < arkTrackBary ) return 0;
    if( arkTrackBaryDecal == 0 )
    {
        if( y != arkTrackBary + 2 )
          return arkTrackbarSprite[ ( x - 3 ) + ( ( y - arkTrackBary ) * 4 ) ];
        return 0;
    }
    if( y == arkTrackBary )
      return arkSplitSpriteDecalageY( arkTrackBaryDecal, arkTrackbarSprite[ x - 3 ], 1 );
    if( y == arkTrackBary + 1 )
      return arkSplitSpriteDecalageY( arkTrackBaryDecal, arkTrackbarSprite[ x - 3 ], 0 ) |
             arkSplitSpriteDecalageY( arkTrackBaryDecal, arkTrackbarSprite[ ( x - 3 ) + 4 ], 1 );
    if( y == arkTrackBary + 2 && arkTrackBaryDecal != 0 )
      return arkSplitSpriteDecalageY( arkTrackBaryDecal, arkTrackbarSprite[ ( x - 3 ) + 4 ], 0 );
    return 0;
}

int arkPannelLive( int x, int y )
{
    if( y < 1 || y > arkLive || x > 121 || x < 119 ) return 0;
    return arkLive_[ x - 119 ];
}

int arkBackground( int x, int y )
{
    if( x <= 105 )
    {
        if( y == 0 ) return arkBackUp[ x ];
        if( y >= 1 && y <= 6 ) return arkTexture[ ( x + 1 ) % 15 ];
        if( y == 7 ) return arkBackDown[ x ];
        return 0;
    }
    return arkBackRight[ ( x - 106 ) + ( y * 22 ) ];
}

// Gameplay render (mode 0) - every layer here already self-gates with its
// own bounds check (upstream wrote them that way), but calling all 6
// functions unconditionally for every one of the 1024 pixels/frame still
// costs 6144 function calls/frame regardless of how cheap each call's own
// body is - without v32opt's inlining (this project's default dev build
// uses SKIP_V32OPT=1), that per-call overhead is real and adds up. Every
// layer here has an easily-computable, narrow footprint (unlike a
// re-scanned sprite list), so gating the *call site* itself by row/x-range
// - same technique already needed for Tris's HUD digits, Bert's plates,
// Doc's grid - cuts the call count to roughly the number of pixels each
// layer actually occupies, instead of 1024 regardless.
void arkTinyFlipGameplay()
{
    md_beginFrame();
    int x, y;

    int ballX = (int)( arkBallxpos - 1 );

    for( y = 0; y < 8; y++ )
    {
        bool blockRows = ( y >= 1 && y <= 6 );
        bool ballRows = ( y >= arkYpos && y <= arkYpos + 1 );
        bool trackRows = ( y >= arkTrackBary && y < arkTrackBary + 3 );
        bool liveRow = ( y >= 1 && y <= arkLive );
        bool levelRow = ( y == 5 || y == 6 );

        for( x = 0; x < 128; x++ )
        {
            int pixel = arkBackground( x, y );

            if( blockRows && x >= 67 && x < 97 ) pixel = pixel | arkDrawBlock( x, y );
            if( ballRows && x >= ballX && x <= ballX + 2 ) pixel = pixel | arkDrawBall( x, y );
            if( trackRows && x >= 3 && x <= 6 ) pixel = pixel | arkDrawTrackBar( x, y );
            if( liveRow && x >= 119 && x <= 121 ) pixel = pixel | arkPannelLive( x, y );
            if( levelRow && x >= 117 && x <= 123 ) pixel = pixel | arkPannelLevel( x, y );

            md_drawColumn( x, y, pixel );
        }
    }
}

void arkTinyFlip( int mode )
{
    if( mode == 0 )
    {
        arkTinyFlipGameplay();
        return;
    }

    md_beginFrame();
    int x, y;
    for( y = 0; y < 8; y++ )
      for( x = 0; x < 128; x++ )
      {
          int pixel;
          if( mode == 1 )
            pixel = arkMain[ x + ( y * 128 ) ];
          else
            pixel = arkBackground( x, y );
          md_drawColumn( x, y, pixel );
      }
}

// -----------------------------------------------------------------------------
//   State machine (replaces loop()'s NEWGAME:/ONE:/NEXTLEVEL:/RESTARTLEVEL:
//   goto-chain and its while(1)s)
// -----------------------------------------------------------------------------

#define ARK_STATE_TITLE             0
#define ARK_STATE_INTRO             1
#define ARK_STATE_PLAYING           2
#define ARK_STATE_LIFE_LOST         3
#define ARK_STATE_LEVEL_CLEAR       4
#define ARK_STATE_LEVEL_CLEAR_PAUSE 5

int arkState;
int arkLevelClearPauseFrames;

void gameTinyArkanoid_init()
{
    InitTinyJoypad();
    arkFrame = 0;
    arkNoteSeqActive = false;
    arkState = ARK_STATE_TITLE;
}

void gameTinyArkanoid_update()
{
    if( arkState == ARK_STATE_TITLE )
    {
        if( isFirePressed() )
        {
            md_armInputFireGate();
            arkRsVarNewGame();
            arkStartNoteSeq( arkMusic1, 92, true );
            arkState = ARK_STATE_INTRO;
            arkTinyFlip( 2 );
            return;
        }
        arkTinyFlip( 1 );
        return;
    }

    if( arkState == ARK_STATE_INTRO )
    {
        arkTinyFlip( 2 );
        if( arkAdvanceNoteSeq() )
        {
            arkResetBall();
            arkState = ARK_STATE_PLAYING;
        }
        return;
    }

    if( arkState == ARK_STATE_LIFE_LOST )
    {
        arkTinyFlip( 0 );
        if( arkAdvanceNoteSeq() )
        {
            if( arkLive > 0 )
            {
                arkLive--;
                arkResetBall();
                arkState = ARK_STATE_PLAYING;
            }
            else
              arkState = ARK_STATE_TITLE;
        }
        return;
    }

    if( arkState == ARK_STATE_LEVEL_CLEAR )
    {
        arkTinyFlip( 0 );
        if( arkAdvanceNoteSeq() )
        {
            if( arkLevelSpeed > 8 ) arkLevelSpeed = arkLevelSpeed - 2;
            arkLevelClearPauseFrames = 24;
            arkState = ARK_STATE_LEVEL_CLEAR_PAUSE;
        }
        return;
    }

    if( arkState == ARK_STATE_LEVEL_CLEAR_PAUSE )
    {
        arkTinyFlip( 2 );
        arkLevelClearPauseFrames--;
        if( arkLevelClearPauseFrames <= 0 )
        {
            arkResetVar();
            arkLevel++;
            arkResetBall();
            arkState = ARK_STATE_PLAYING;
        }
        return;
    }

    // ARK_STATE_PLAYING
    //
    // Upstream's own while(1) loop has no vsync wait at all - Frame
    // increments (and the paddle-read/ball-update modulo checks gated on
    // it) run as fast as the bare AVR loop iterates, which is far faster
    // than the display refresh; only the actual redraw is throttled
    // (`Frame%32==0`). Porting this as "one Frame increment per real
    // engine frame" (the usual approach for this project's other ports)
    // silently made the whole game ~30x slower than intended here,
    // because paddle reads/ball updates are gated on Frame at all -
    // unlike those other games, which run their full logic+redraw
    // together once per tick with no such internal throttle. Fixed by
    // decoupling the two rates: run ARK_TICKS_PER_FRAME logic ticks per
    // real engine frame (so paddle response and ball speed land at a
    // normal arcade pace) but still call arkTinyFlip() only once at the
    // end, keeping the redraw itself at a real, steady 60fps like every
    // other port here.
    #define ARK_TICKS_PER_FRAME 8

    int tick;
    for( tick = 0; tick < ARK_TICKS_PER_FRAME; tick++ )
    {
        if( arkFrame % 8 == 0 )
        {
            // The game's own art (title screen, panels) is drawn sideways,
            // as if meant to be viewed with the display rotated - since
            // Vircon32's screen can't actually rotate, UP and LEFT are
            // both accepted as "paddle toward the top" and DOWN/RIGHT as
            // "paddle toward the bottom", so it feels natural to play
            // either holding the d-pad as originally oriented or rotated
            // to match the sideways art. Note this is swapped from
            // upstream's own TrackBary/TrackBaryDecal wiring (increasing
            // them moves the paddle to a *larger* page index, i.e. further
            // down the screen) - ported verbatim at first, which made a
            // real gamepad's UP button move the paddle down and vice
            // versa; swapped here since that reads as inverted controls
            // on real hardware even though it faithfully matched upstream.
            if( isDownPressed() || isRightPressed() )
            {
                if( arkTrackBaryDecal < 7 )
                {
                    if( arkTrackBaryDecal + ( arkTrackBary * 8 ) < 44 ) arkTrackBaryDecal++;
                }
                else
                {
                    arkTrackBaryDecal = 0;
                    arkTrackBary++;
                }
            }
            if( isUpPressed() || isLeftPressed() )
            {
                if( arkTrackBaryDecal > 0 )
                {
                    if( arkTrackBaryDecal + ( arkTrackBary * 8 ) > 4 ) arkTrackBaryDecal--;
                }
                else
                {
                    arkTrackBaryDecal = 7;
                    arkTrackBary--;
                }
            }
            if( arkLaunch == 0 && isFirePressed() ) arkLaunch = 1;
            if( arkLaunch == 0 )
            {
                arkBallypos = ( ( arkTrackBary * 8 ) + arkTrackBaryDecal ) + 10;
                arkSimBallypos = arkBallypos;
            }
        }

        if( arkFrame % arkLevelSpeed == 0 ) arkUpdateBall();

        if( arkFrame == 48 )
        {
            if( arkAnimReflect < 3 ) arkAnimReflect++;
            if( arkBallMissing() )
            {
                arkStartNoteSeq( arkLifeLostNotes, 8, false );
                arkState = ARK_STATE_LIFE_LOST;
                arkTinyFlip( 0 );
                return;
            }
            if( arkCheckLevelEnded() )
            {
                arkStartNoteSeq( arkLevelClearNotes, 10, false );
                arkState = ARK_STATE_LEVEL_CLEAR;
                arkTinyFlip( 0 );
                return;
            }
        }

        if( arkFrame < 64 ) arkFrame++; else arkFrame = 1;
    }

    arkTinyFlip( 0 );
}
